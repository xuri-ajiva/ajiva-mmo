    private const string Namespace = "NetworkPackets";
    private const string AttributeName = "NetworkPacketAttribute";
    private const string AutoGenHeader = "// <auto-generated/>";

    private const string AttributeSourceCode =
        $$"""
          {{AutoGenHeader}}

          namespace {{Namespace}}
          {
              [global::System.AttributeUsage(global::System.AttributeTargets.Class | global::System.AttributeTargets.Struct)]
              public class {{AttributeName}} : global::System.Attribute
              {
                  public ushort PacketId { get; }

                  public {{AttributeName}}(ushort packetId)
                  {
                      PacketId = packetId;
                  }
              }
          }
          """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Add the marker attribute to the compilation.
        context.RegisterPostInitializationOutput(ctx => ctx.AddSource(
            "NetworkPacketAttribute.g.cs",
            SourceText.From(AttributeSourceCode, Encoding.UTF8)));

        // Filter classes annotated with the [NetworkPacket] attribute. Only filtered Syntax Nodes can trigger code generation.
        var provider = context.SyntaxProvider
            .CreateSyntaxProvider(
                (s, _) => s is TypeDeclarationSyntax,
                (ctx, _) => GetClassDeclarationForSourceGen(ctx))
            .Where(t => t.reportAttributeFound)
            .Select((t, _) => (t.Item1, t.Item2));

        // Generate the source code.
        context.RegisterSourceOutput(context.CompilationProvider.Combine(provider.Collect()),
            ((ctx, t) => GenerateCode(ctx, t.Left, t.Right)));
    }

    private static (TypeDeclarationSyntax, ushort, bool reportAttributeFound) GetClassDeclarationForSourceGen(
        GeneratorSyntaxContext context)
    {
        var classDeclarationSyntax = (TypeDeclarationSyntax)context.Node;

        // Go through all attributes of the class.
        foreach (AttributeListSyntax attributeListSyntax in classDeclarationSyntax.AttributeLists)
        foreach (AttributeSyntax attributeSyntax in attributeListSyntax.Attributes)
        {
            if (ModelExtensions.GetSymbolInfo(context.SemanticModel, attributeSyntax).Symbol is not IMethodSymbol
                attributeSymbol)
                continue; // if we can't get the symbol, ignore it

            string attributeName = attributeSymbol.ContainingType.ToDisplayString();

            // Check the full name of the [Report] attribute.
            if (attributeName == $"{Namespace}.{AttributeName}")
            {
                if (attributeSyntax.ArgumentList is { Arguments: { Count: > 0 } arguments })
                {
                    if (arguments[0].Expression is not LiteralExpressionSyntax literalExpression)
                        throw new NotSupportedException("Only constant values are supported.");
                    return (classDeclarationSyntax, (ushort)((int)literalExpression.Token.Value!), true);
                }
            }
        }

        return (classDeclarationSyntax, 0, false);
    }

    private void GenerateCode(SourceProductionContext context, Compilation compilation,
        ImmutableArray<(TypeDeclarationSyntax, ushort)> declarations)
    {
        var packetTypes = new List<EnumMemberDeclarationSyntax>();
        HashSet<ushort> packageTypeIds = [];
        var classesAndFields =
            new List<(string namesp, string className, List<(TypeSyntax Type, string fieldName)> fields)>();

        // Go through all filtered class declarations.
        foreach (var (classDeclarationSyntax, packageTypeId) in declarations)
        {
            // We need to get semantic model of the class to retrieve metadata.
            var semanticModel = compilation.GetSemanticModel(classDeclarationSyntax.SyntaxTree);

            // Symbols allow us to get the compile-time information.
            if (ModelExtensions.GetDeclaredSymbol(semanticModel, classDeclarationSyntax) is not INamedTypeSymbol
                classSymbol)
                continue;

            var namespaceName = classSymbol.ContainingNamespace.ToDisplayString();

            // 'Identifier' means the token of the node. Get class name from the syntax node.
            var className = classDeclarationSyntax.Identifier.Text;

            var code = GenerateIMessageSerializableInterface(semanticModel, classSymbol, classDeclarationSyntax,
                namespaceName, className, out var fields);

            // Add the source code to the compilation.
            context.AddSource($"{className}.g.cs", SourceText.From(code, Encoding.UTF8));

            var enumId = packageTypeId;
            while (packageTypeIds.Contains(enumId))
            {
                enumId += FindCoprimeIncrement(enumId);
            }

            packetTypes.Add(EqualsValueFor(className, enumId));
            classesAndFields.Add((namespaceName, className, fields));
        }

        var unit = CompilationUnit()
            .AddMembers(FileScopedNamespaceDeclaration(IdentifierName(Namespace)))
            .AddMembers(
                EnumDeclaration("PacketType")
                    .AddModifiers(Token(SyntaxKind.PublicKeyword))
                    .AddBaseListTypes(SimpleBaseType(PredefinedType(Token(SyntaxKind.UShortKeyword))))
                    .AddMembers(packetTypes.ToArray())
            )
            .NormalizeWhitespace();


        context.AddSource("PacketType.g.cs", SourceText.From(
            $"""
             // <auto-generated/>
             #nullable enable
             #nullable disable warnings

             {unit.ToString()}
             """, Encoding.UTF8));

        GenerateHandlers(context, classesAndFields);
    }

    private static void GenerateHandlers(SourceProductionContext context,
        List<(string namesp, string className, List<(TypeSyntax Type, string fieldName)> fields)> classesAndFields)
    {
        var asyncHandler = InterfaceDeclaration("IUniversalAsyncMessageHandler")
            .AddModifiers(Token(SyntaxKind.PublicKeyword));

        var handler = InterfaceDeclaration("IUniversalMessageHandler")
            .AddModifiers(Token(SyntaxKind.PublicKeyword));

        var asyncHandlerMembers = new List<MemberDeclarationSyntax>();
        var handlerMembers = new List<MemberDeclarationSyntax>();

        foreach (var (namesp, className, _) in classesAndFields)
        {
            var fullNameOfClass = namesp + "." + className;
            asyncHandlerMembers.Add(MethodDeclaration(IdentifierName("global::System.Threading.Tasks.Task"), "Handle")
                .AddModifiers(Token(SyntaxKind.PublicKeyword))
                .WithParameterList(ParameterList(SingletonSeparatedList(
                    Parameter(Identifier("message"))
                        .WithType(IdentifierName(fullNameOfClass))
                )))
                .WithExpressionBody(ArrowExpressionClause(MemberAccessExpression(
                        SyntaxKind.SimpleMemberAccessExpression,
                        IdentifierName("global::System.Threading.Tasks.Task"),
                        IdentifierName("CompletedTask")
                    )
                )).WithSemicolonToken(Token(SyntaxKind.SemicolonToken))
            );

            handlerMembers.Add(MethodDeclaration(PredefinedType(Token(SyntaxKind.VoidKeyword)), "Handle")
                .AddModifiers(Token(SyntaxKind.PublicKeyword))
                .WithParameterList(ParameterList(SingletonSeparatedList(
                    Parameter(Identifier("message"))
                        .WithType(IdentifierName(fullNameOfClass))
                )))
                .WithBody(Block())
            );
        }

        var unit = CompilationUnit()
            .AddMembers(FileScopedNamespaceDeclaration(IdentifierName(Namespace)))
            .AddMembers(asyncHandler.AddMembers(asyncHandlerMembers.ToArray()))
            .AddMembers(handler.AddMembers(handlerMembers.ToArray()))
            .NormalizeWhitespace();

        context.AddSource("UniversalMessageHandlers.g.cs", SourceText.From(
            $"""
             // <auto-generated/>
             #nullable enable
             #nullable disable warnings

             {unit.ToString()}
             """, Encoding.UTF8));


        var asyncExpressionClauses = new List<SwitchExpressionArmSyntax>();
        var expressionClauses = new List<SwitchSectionSyntax>();
        foreach (var (namesp, className, _) in classesAndFields)
        {
            asyncExpressionClauses.Add(SwitchExpressionArm(
                TypePattern(IdentifierName("PacketType." + className)),
                InvocationExpression(
                    MemberAccessExpression(
                        SyntaxKind.SimpleMemberAccessExpression,
                        IdentifierName("handler"),
                        IdentifierName("Handle")
                    )
                ).WithArgumentList(ArgumentList(SingletonSeparatedList(
                    Argument(InvocationExpression(
                        MemberAccessExpression(
                            SyntaxKind.SimpleMemberAccessExpression,
                            IdentifierName(namesp + "." + className),
                            IdentifierName("FromMessage")
                        )).WithArgumentList(ArgumentList(SingletonSeparatedList(
                            Argument(IdentifierName("message"))
                        ))
                    ))
                )))
            ));

            expressionClauses.Add(SwitchSection()
                .AddLabels(CaseSwitchLabel(IdentifierName("PacketType." + className)))
                .AddStatements(ExpressionStatement(
                        InvocationExpression(
                            MemberAccessExpression(
                                SyntaxKind.SimpleMemberAccessExpression,
                                IdentifierName("handler"),
                                IdentifierName("Handle")
                            )
                        ).WithArgumentList(ArgumentList(SingletonSeparatedList(
                            Argument(InvocationExpression(
                                MemberAccessExpression(
                                    SyntaxKind.SimpleMemberAccessExpression,
                                    IdentifierName(namesp + "." + className),
                                    IdentifierName("FromMessage")
                                )).WithArgumentList(ArgumentList(SingletonSeparatedList(
                                    Argument(IdentifierName("message"))
                                ))
                            ))
                        )))
                    ),
                    BreakStatement())
            );
        }

        asyncExpressionClauses.Add(SwitchExpressionArm(
            DiscardPattern(),
            ThrowExpression(
                ObjectCreationExpression(
                    IdentifierName("ArgumentOutOfRangeException")
                ).WithArgumentList(ArgumentList())
            )
        ));

        var asyncMessageHandlerMethod =
            MethodDeclaration(IdentifierName("global::System.Threading.Tasks.Task"), "HandleMessage")
                .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.StaticKeyword),
                    Token(SyntaxKind.AsyncKeyword))
                .AddParameterListParameters(
                    Parameter(Identifier("handler"))
                        .WithType(IdentifierName("IUniversalAsyncMessageHandler"))
                        .WithModifiers(TokenList(Token(SyntaxKind.ThisKeyword))),
                    Parameter(Identifier("message"))
                        .WithType(IdentifierName("global::Riptide.Message"))
                ).WithBody(Block()
                    .AddStatements(
                        LocalDeclarationStatement(
                            VariableDeclaration(IdentifierName("PacketType"))
                                .WithVariables(SingletonSeparatedList(
                                    VariableDeclarator(Identifier("type"))
                                        .WithInitializer(EqualsValueClause(CastExpression(
                                            IdentifierName("PacketType"),
                                            InvocationExpression(MemberAccessExpression(
                                                SyntaxKind.SimpleMemberAccessExpression,
                                                IdentifierName("message"),
                                                IdentifierName("GetUShort")
                                            ))
                                        )))
                                ))
                        ),
                        LocalDeclarationStatement(
                            VariableDeclaration(IdentifierName("var"))
                                .WithVariables(SingletonSeparatedList(VariableDeclarator(Identifier("task"))
                                    .WithInitializer(EqualsValueClause(SwitchExpression(
                                            IdentifierName("type"))
                                        .WithArms(SeparatedList(asyncExpressionClauses))
                                    ))
                                ))
                        ),
                        ExpressionStatement(
                            AwaitExpression(IdentifierName("task"))
                        ),
                        ExpressionStatement(InvocationExpression(MemberAccessExpression(
                            SyntaxKind.SimpleMemberAccessExpression,
                            IdentifierName("message"),
                            IdentifierName("Release")
                        )))
                    ));


        var messageHandlerMethod =
            MethodDeclaration(PredefinedType(Token(SyntaxKind.VoidKeyword)), "HandleMessage")
                .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.StaticKeyword))
                .AddParameterListParameters(
                    Parameter(Identifier("handler"))
                        .WithType(IdentifierName("IUniversalMessageHandler"))
                        .WithModifiers(TokenList(Token(SyntaxKind.ThisKeyword))),
                    Parameter(Identifier("message"))
                        .WithType(IdentifierName("global::Riptide.Message"))
                ).WithBody(Block()
                    .AddStatements(
                        LocalDeclarationStatement(
                            VariableDeclaration(IdentifierName("PacketType"))
                                .WithVariables(SingletonSeparatedList(
                                    VariableDeclarator(Identifier("type"))
                                        .WithInitializer(EqualsValueClause(CastExpression(
                                            IdentifierName("PacketType"),
                                            InvocationExpression(MemberAccessExpression(
                                                SyntaxKind.SimpleMemberAccessExpression,
                                                IdentifierName("message"),
                                                IdentifierName("GetUShort")
                                            ))
                                        )))
                                ))
                        ),
                        SwitchStatement(IdentifierName("type"))
                            .AddSections(expressionClauses.ToArray()),
                        ExpressionStatement(InvocationExpression(MemberAccessExpression(
                            SyntaxKind.SimpleMemberAccessExpression,
                            IdentifierName("message"),
                            IdentifierName("Release")
                        )))
                    ));

        unit = CompilationUnit()
            .AddMembers(FileScopedNamespaceDeclaration(IdentifierName(Namespace)))
            .AddMembers(ClassDeclaration("MessageHandlerExtensions")
                .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.StaticKeyword))
                .AddMembers(asyncMessageHandlerMethod)
                .AddMembers(messageHandlerMethod)
            )
            .NormalizeWhitespace();

        context.AddSource("MessageHandlerExtensions.g.cs", SourceText.From(
            $"""
             // <auto-generated/>
             #nullable enable
             #nullable disable warnings

             {unit.ToString()}
             """, Encoding.UTF8));
    }

    private static EnumMemberDeclarationSyntax EqualsValueFor(string className, ushort enumId)
    {
        return EnumMemberDeclaration(className)
            .WithEqualsValue(
                EqualsValueClause(
                    LiteralExpression(
                        SyntaxKind.NumericLiteralExpression,
                        Literal(enumId)
                    )
                ));
    }

    private static string GenerateIMessageSerializableInterface(SemanticModel semanticModel, INamedTypeSymbol symbol,
        TypeDeclarationSyntax declarationSyntax, string namespaceName,
        string className, out List<(TypeSyntax Type, string fieldName)> fields)
    {
        var accessibilityModifier = symbol.DeclaredAccessibility switch
        {
            Accessibility.Public => Token(SyntaxKind.PublicKeyword),
            Accessibility.Internal => Token(SyntaxKind.InternalKeyword),
            _ => throw new NotSupportedException("Only public and internal classes are supported.")
        };

        var namespaceDef =
            FileScopedNamespaceDeclaration(IdentifierName(namespaceName));

        // Building Compilation unit
        var syntaxRoot = semanticModel.SyntaxTree.GetRoot();
        var usingDirectives = syntaxRoot.ChildNodes()
            .OfType<UsingDirectiveSyntax>()
            .Select(d => d.WithoutTrivia()) // Removes #ifdef, etc.
            .ToArray();

        var classDecle = ClassDeclaration(className)
            .AddModifiers(accessibilityModifier, Token(SyntaxKind.PartialKeyword))
            .WithTypeParameterList(symbol.TypeParameters.Length > 0
                ? TypeParameterList(SeparatedList(
                    symbol.TypeParameters.Select(p => TypeParameter(p.Name))))
                : null)
            .AddBaseListTypes(SimpleBaseType(IdentifierName("global::Riptide.IMessageSerializable")));


        fields = new List<(TypeSyntax Type, string fieldName)>();
        foreach (var parameter in declarationSyntax.ParameterList!.Parameters)
        {
            var fieldName = "_" + parameter.Identifier.Text;
            fields.Add((parameter.Type!, fieldName));
            classDecle = classDecle.AddMembers(FieldDeclaration(
                        VariableDeclaration(parameter.Type!)
                            .WithVariables(
                                SingletonSeparatedList(
                                    VariableDeclarator(Identifier(fieldName))
                                        .WithInitializer(
                                            EqualsValueClause(
                                                IdentifierName(parameter.Identifier.Text)
                                            )
                                        )
                                )
                            )
                    )
                    .WithModifiers(TokenList(Token(SyntaxKind.PublicKeyword))),
                PropertyDeclaration(parameter.Type!,
                        Identifier(ToPascalCase(parameter.Identifier.Text)))
                    .WithModifiers(TokenList(Token(SyntaxKind.PublicKeyword)))
                    .WithAccessorList(
                        AccessorList(
                            List(
                                [
                                    AccessorDeclaration(SyntaxKind.GetAccessorDeclaration)
                                        .WithExpressionBody(
                                            ArrowExpressionClause(
                                                MemberAccessExpression(
                                                    SyntaxKind.SimpleMemberAccessExpression,
                                                    ThisExpression(),
                                                    IdentifierName(fieldName)
                                                )
                                            )
                                        ).WithSemicolonToken(Token(SyntaxKind.SemicolonToken)),
                                    AccessorDeclaration(SyntaxKind.SetAccessorDeclaration)
                                        .WithExpressionBody(
                                            ArrowExpressionClause(
                                                AssignmentExpression(
                                                    SyntaxKind.SimpleAssignmentExpression,
                                                    MemberAccessExpression(
                                                        SyntaxKind.SimpleMemberAccessExpression,
                                                        ThisExpression(),
                                                        IdentifierName(fieldName)
                                                    ),
                                                    IdentifierName("value")
                                                )
                                            )
                                        ).WithSemicolonToken(Token(SyntaxKind.SemicolonToken))
                                ]
                            )
                        )
                    )
            );
        }


        /*
         public static {this} FromMessage(global::Riptide.Message message)
         {{
             return new {this}(Message.Get{Type}(message) ...);
         }}

         */
        classDecle = classDecle.AddMembers(
            MethodDeclaration(IdentifierName(className), "FromMessage")
                .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.StaticKeyword))
                .AddParameterListParameters(Parameter(Identifier("message"))
                    .WithType(IdentifierName("global::Riptide.Message")))
                .WithBody(Block(
                    ReturnStatement(
                        ObjectCreationExpression(IdentifierName(className))
                            .WithArgumentList(
                                ArgumentList(
                                    SeparatedList(
                                        fields.Select(f => Argument(
                                            InvocationExpression(
                                                MemberAccessExpression(
                                                    SyntaxKind.SimpleMemberAccessExpression,
                                                    IdentifierName("message"),
                                                    IdentifierName(TypeToGetMethod(f.Type))
                                                )
                                            )
                                        ))
                                    )
                                )
                            )
                    )
                ))
        );

        List<StatementSyntax> toMessageBody =
        [
            LocalDeclarationStatement(
                VariableDeclaration(IdentifierName("var"))
                    .WithVariables(SingletonSeparatedList(
                        VariableDeclarator(Identifier("msg"))
                            .WithInitializer(EqualsValueClause(
                                InvocationExpression(MemberAccessExpression(
                                    SyntaxKind.SimpleMemberAccessExpression,
                                    IdentifierName("global::Riptide.Message"),
                                    IdentifierName("Create"))
                                ).WithArgumentList(ArgumentList(SingletonSeparatedList(
                                    Argument(IdentifierName("sendMode")))))
                            )))
                    )),
            ExpressionStatement(InvocationExpression(
                    MemberAccessExpression(
                        SyntaxKind.SimpleMemberAccessExpression,
                        IdentifierName("msg"),
                        IdentifierName("AddUShort")
                    )).WithArgumentList(ArgumentList(SingletonSeparatedList(
                    Argument(CastExpression(
                        PredefinedType(Token(SyntaxKind.UShortKeyword)),
                        IdentifierName("PacketType." + className)
                    ))
                )))
            )
        ];
        foreach (var f in fields)
        {
            toMessageBody.Add(ExpressionStatement(InvocationExpression(
                    MemberAccessExpression(
                        SyntaxKind.SimpleMemberAccessExpression,
                        IdentifierName("msg"),
                        IdentifierName(TypeToAddMethod(f.Type))
                    )).WithArgumentList(ArgumentList(SingletonSeparatedList(
                    Argument(IdentifierName(f.fieldName))
                )))
            ));
        }

        toMessageBody.Add(ReturnStatement(IdentifierName("msg")));

        classDecle = classDecle.AddMembers(
            MethodDeclaration(PredefinedType(Token(SyntaxKind.VoidKeyword)), "Send")
                .AddModifiers(Token(SyntaxKind.PublicKeyword))
                .AddParameterListParameters(
                    Parameter(Identifier("connection"))
                        .WithType(IdentifierName("global::Riptide.Connection")),
                    Parameter(Identifier("sendMode"))
                        .WithType(IdentifierName("global::Riptide.MessageSendMode"))
                )
                .WithBody(Block(ExpressionStatement(InvocationExpression(
                        MemberAccessExpression(
                            SyntaxKind.SimpleMemberAccessExpression,
                            IdentifierName("connection"),
                            IdentifierName("Send")
                        ))
                    .WithArgumentList(ArgumentList(SingletonSeparatedList(
                        Argument(InvocationExpression(MemberAccessExpression(
                                SyntaxKind.SimpleMemberAccessExpression,
                                ThisExpression(),
                                IdentifierName("ToMessage")
                            ))
                            .WithArgumentList(ArgumentList(
                                SingletonSeparatedList(
                                    Argument(IdentifierName("sendMode"))
                                ))
                            ))
                    ))))
                )),
            MethodDeclaration(IdentifierName("global::Riptide.Message"), "ToMessage")
                .AddModifiers(Token(SyntaxKind.PublicKeyword))
                .AddParameterListParameters(
                    Parameter(Identifier("sendMode"))
                        .WithType(IdentifierName("global::Riptide.MessageSendMode"))
                )
                .WithBody(Block(toMessageBody))
        );

        var unit = CompilationUnit()
            .AddUsings(usingDirectives)
            .AddMembers(namespaceDef)
            .AddMembers(classDecle.AddMembers(
                GenerateSerializationMethods(fields),
                GenerateDeserializationMethods(fields)
            ))
            .NormalizeWhitespace();


        return $"""
                // <auto-generated/>
                #nullable enable
                #nullable disable warnings

                {unit.ToString()}
                """;
    }

    private static string TypeToAddMethod(TypeSyntax type)
    {
        return "Add" + _knownTypeLookup[type.ToString()];
    }

    private static string TypeToGetMethod(TypeSyntax type)
    {
        var typename = type.ToString();

        return "Get" + _knownTypeLookup[typename];
    }

    private static string ToPascalCase(string text)
    {
        return text.Substring(0, 1).ToUpper() + text.Substring(1);
    }

    private static MemberDeclarationSyntax GenerateDeserializationMethods(
        List<(TypeSyntax Type, string fieldName)> fields)
    {
        var deserializeMethod = MethodDeclaration(PredefinedType(Token(SyntaxKind.VoidKeyword)), "Deserialize")
            .AddModifiers(Token(SyntaxKind.PublicKeyword))
            .AddParameterListParameters(Parameter(Identifier("message"))
                .WithType(IdentifierName("global::Riptide.Message")));

        var deserializeStatements = new SyntaxList<StatementSyntax>();

        foreach (var member in fields)
        {
            // call message.Get(out {fieldName})
            deserializeStatements = deserializeStatements.Add(
                ExpressionStatement(
                    InvocationExpression(
                        MemberAccessExpression(
                            SyntaxKind.SimpleMemberAccessExpression,
                            IdentifierName("message"),
                            IdentifierName("Get")
                        )
                    ).WithArgumentList(
                        ArgumentList(
                            SingletonSeparatedList(
                                Argument(
                                    MemberAccessExpression(
                                        SyntaxKind.SimpleMemberAccessExpression,
                                        IdentifierName("this"),
                                        IdentifierName(member.fieldName)
                                    )
                                ).WithRefOrOutKeyword(Token(SyntaxKind.OutKeyword))
                            )
                        )
                    )
                )
            );
        }

        return deserializeMethod.WithBody(Block(deserializeStatements));
    }

    private static MemberDeclarationSyntax GenerateSerializationMethods(
        List<(TypeSyntax Type, string fieldName)> fields)
    {
        var serializeMethod = MethodDeclaration(PredefinedType(Token(SyntaxKind.VoidKeyword)), "Serialize")
            .AddModifiers(Token(SyntaxKind.PublicKeyword))
            .AddParameterListParameters(Parameter(Identifier("message"))
                .WithType(IdentifierName("global::Riptide.Message")));

        var serializeStatements = new SyntaxList<StatementSyntax>();

        foreach (var member in fields)
        {
            // call message.Add({fieldName})
            serializeStatements = serializeStatements.Add(
                ExpressionStatement(
                    InvocationExpression(
                        MemberAccessExpression(
                            SyntaxKind.SimpleMemberAccessExpression,
                            IdentifierName("message"),
                            IdentifierName("Add")
                        )
                    ).WithArgumentList(
                        ArgumentList(
                            SingletonSeparatedList(
                                Argument(
                                    IdentifierName(member.fieldName)
                                )
                            )
                        )
                    )
                )
            );
        }

        return serializeMethod.WithBody(Block(serializeStatements));
    }

    // Helper function to find a coprime increment (important for full cycle)
    private static ushort FindCoprimeIncrement(ushort count)
    {
        if (count <= 1) return 1; // For 0 or 1 elements, increment 1 is fine

        for (ushort increment = 2; increment < count; ++increment)
        {
            if (Gcd(increment, count) == 1) // Greatest Common Divisor is 1 (coprime)
            {
                return increment;
            }
        }

        return 1; // Fallback, but ideally we find a coprime increment
    }

    // Euclidean Algorithm for Greatest Common Divisor (GCD)
    private static int Gcd(ushort a, ushort b)
    {
        while (b != 0)
        {
            var temp = b;
            b = (ushort)(a % b);
            a = temp;
        }

        return a;
    }
