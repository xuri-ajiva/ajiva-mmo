using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Diagnostics.CodeAnalysis;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace InterceptionTraceGenerator;

[Generator]
public class InterceptionSourceGenerator : IIncrementalGenerator
{
    private const string Namespace = "Interception";
    private static readonly string[] ExcludedClasses = ["Common.Instrumentation"];
    private static readonly string[] ExcludedNamespaces = ["System.Diagnostics", "Interception"];
    private static readonly string[] ExcludedAttributes = ["ExcludeFromInterception", "CompilerGenerated"];

    private static bool CheckAttributes(AttributeData arg) =>
        arg.AttributeClass is not null && CheckAttributName(arg.AttributeClass.Name);

    private static bool CheckAttributName(string name) => ExcludedAttributes.Contains(name) ||
                                                          ExcludedAttributes.Contains(name.Replace("Attribute", ""));

    [Experimental("RSEXPERIMENTAL002")]
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(initializationContext => initializationContext.AddSource(
            "InterceptsLocationAttribute.g.cs",
            $"""
             // <auto-generated/>
             using System;

             namespace {Namespace};
             [AttributeUsage(AttributeTargets.All, Inherited = false, AllowMultiple = false)]
             internal sealed class ExcludeFromInterception : Attribute;
             """));

        var provider = context.SyntaxProvider
            .CreateSyntaxProvider((node, token) => FilterNode(node),
                (syntaxContext, token) => syntaxContext);

        // Generate the source code.
        context.RegisterSourceOutput(context.CompilationProvider.Combine(provider.Collect()),
            ((ctx, t) => GenerateCode(ctx, t.Left, t.Right)));
    }

    private static bool FilterNode(SyntaxNode node)
    {
        if (node is not InvocationExpressionSyntax invocation)
            return false;

        // Check if the invocation is within a class that has specific attributes
        var containingClass = invocation.Ancestors().OfType<ClassDeclarationSyntax>().FirstOrDefault();
        if (!(containingClass?.AttributeLists.Count > 0)) return true;
        // Check for specific attributes you want to exclude

        foreach (var syntax in containingClass.AttributeLists)
        {
            if (syntax.Attributes.Any(attribute => CheckAttributName(attribute.Name.ToString())))
            {
                return false;
            }
        }

        return true;
    }

    [Experimental("RSEXPERIMENTAL002")]
    private void GenerateCode(SourceProductionContext ctx, Compilation compilation,
        ImmutableArray<GeneratorSyntaxContext> classes)
    {
        HashSet<string> usings = new HashSet<string>
        {
            "System",
            "System.Runtime.CompilerServices",
            "Common"
        };
        StringBuilder sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine($"namespace {Namespace};");

        sb.Append("public static class InterceptorsGenerated {");

        foreach (var node in classes)
        {
            var invocation = (InvocationExpressionSyntax)node.Node;

            var semanticModel = node.SemanticModel;
            var model = compilation.GetSemanticModel(invocation.SyntaxTree);
            if (ModelExtensions.GetSymbolInfo(semanticModel, invocation).Symbol is not IMethodSymbol methodSymbol)
                continue;
            if (methodSymbol.IsGenericMethod) continue;
            if (methodSymbol.IsStatic) continue;
            if (methodSymbol.IsExtensionMethod) continue;
            if (methodSymbol.IsVirtual) continue;
            if (methodSymbol.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal
                or Accessibility.NotApplicable)) continue;

            if (ExcludedClasses.Contains(methodSymbol.ContainingType?.ToDisplayString()))
                continue;
            if (ExcludedNamespaces.Contains(methodSymbol.ContainingNamespace?.ToDisplayString()))
                continue;
            if (methodSymbol.GetAttributes().Any(CheckAttributes))
                continue;

            if (semanticModel.GetInterceptableLocation(invocation) is not { } interceptableLocation)
                continue;

            var receiverType = methodSymbol.ReceiverType;
            if (receiverType is null) continue;
            if (receiverType.GetAttributes().Any(CheckAttributes))
                continue;

            foreach (var containingSyntax in invocation.Ancestors().OfType<MethodDeclarationSyntax>())
            {
                if (containingSyntax?.TypeParameterList != null)
                    goto superbreak; // Skip calls within generic methods
            }

            foreach (var containingSyntax in invocation.Ancestors().OfType<TypeDeclarationSyntax>())
            {
                if (containingSyntax?.TypeParameterList != null)
                    goto superbreak; // Skip calls within generic methods
            }

            usings.Add(methodSymbol.ContainingNamespace.ToDisplayString());
            foreach (var usingDirectiveSyntax in invocation.SyntaxTree.GetRoot().ChildNodes()
                         .OfType<UsingDirectiveSyntax>())
            {
                if (usingDirectiveSyntax.Alias is not null)
                {
                    continue;
                }

                if (!usingDirectiveSyntax.StaticKeyword.IsMissing)
                {
                    continue;
                }

                usings.Add(usingDirectiveSyntax.Name!.ToString());
            }

            var returnType = methodSymbol.ReturnType;
            var methodName = methodSymbol.Name;
            var parameters = methodSymbol.Parameters;

            if (parameters.Any(x => x.IsThis)) continue; // skip extension methods for now

            //Debugger.Launch();
            var prefix = methodSymbol.ReceiverType!.IsValueType
                ? methodSymbol.ReceiverType.IsReadOnly || methodSymbol.IsReadOnly
                    ? "in this"
                    : "ref this"
                : "this";
            var paramList = string.Join(", ",
            [
                $"{methodSymbol.ReceiverType} __target__",
                ..parameters.Select(p => p.ToString())
            ]);

            sb.AppendLine();
            sb.AppendLine(interceptableLocation.GetInterceptsLocationAttributeSyntax());
            sb.Append($"    internal static unsafe ");
            if (methodSymbol.ReturnsByRef)
                sb.Append("ref ");
            if (methodSymbol.ReturnsByRefReadonly)
                sb.Append("readonly ");

            sb.AppendLine($"{returnType} {methodName}{GetRandomName()}({prefix} {paramList}) {{");
            sb.AppendLine(
                $"        using var __trace__ = Instrumentation.NamedTrace(\"{methodSymbol.ContainingType!.ToDisplayString()}.{methodName}\");");
            sb.Append("        ");
            if (returnType.SpecialType != SpecialType.System_Void)
                sb.Append("return ");
            if (methodSymbol.ReturnsByRef)
                sb.Append("ref ");
            if (methodSymbol.ReturnsByRefReadonly)
                sb.Append("readonly ");
            sb.AppendLine($"__target__.{methodName}({string.Join(", ", parameters.Select(ArgName))});");
            sb.AppendLine("    }");

            superbreak:
            {
            }
        }

        sb.AppendLine("}");
        ctx.AddSource("InterceptorsGenerated.g.cs",
            usings.Select(x => $"using {x};").Aggregate((a, b) => a + "\n" + b) + "\n" +
            sb);
    }


    private static string ArgName(IParameterSymbol p)
    {
        return p.RefKind switch
        {
            RefKind.None => p.Name,
            RefKind.Ref => "ref " + p.Name,
            RefKind.Out => "out " + p.Name,
            RefKind.In => "in " + p.Name,
            RefKind.RefReadOnlyParameter => "ref readonly " + p.Name,
            _ => "" //throw new ArgumentOutOfRangeException()
        };
    }

    private static string GetRandomName()
    {
        return "_" + Guid.NewGuid().ToString("N");
    }
}
