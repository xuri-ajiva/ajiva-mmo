    [Experimental("RSEXPERIMENTAL002")]
    private static string GetRandomName(InterceptableLocation interceptableLocation)
    {
        return interceptableLocation.Data.Replace("=", "").Replace("/", "_").Replace("+", "_").Replace("-", "_");
    }
