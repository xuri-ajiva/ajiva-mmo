namespace WgslGenerator;

/// <summary>
/// A sample source generator that creates a custom report based on class properties. The target class should be annotated with the 'Generators.ReportAttribute' attribute.
/// When using the source code as a baseline, an incremental source generator is preferable because it reduces the performance overhead.
/// </summary>
[Generator]
public class WgslShaderGenerator : IIncrementalGenerator
{
    private const string Namespace = "Generators";
    private const string AttributeName = "GenerateShaderAttribute";
    private const string ShaderSource = "ShaderSource";

    private const string AttributeSourceCode =
        $$"""
          // <auto-generated/>
          #pragma warning disable CS9113
          using System;
          namespace {{Namespace}};

          [AttributeUsage(AttributeTargets.Class)]
          public class {{AttributeName}} : Attribute;

          [AttributeUsage(AttributeTargets.Field | AttributeTargets.Parameter)]
          public partial class Builtin(string name) : Attribute;

          [AttributeUsage(AttributeTargets.Field | AttributeTargets.Parameter)]
          public partial class Location(uint location) : Attribute;

          [AttributeUsage(AttributeTargets.Method)]
          public partial class VertexShader : Attribute;

          [AttributeUsage(AttributeTargets.Method)]
          public partial class FragmentShader : Attribute;

          [AttributeUsage(AttributeTargets.Method)]
          public partial class ComputeShader : Attribute;

          [AttributeUsage(AttributeTargets.Method)]
          public partial class WorkgroupSize(u32 x, u32 y = 1, u32 z = 1) : Attribute;

          [AttributeUsage(AttributeTargets.Field | AttributeTargets.Property)]
          public partial class Group(uint id) : Attribute;

          [AttributeUsage(AttributeTargets.Field | AttributeTargets.Property)]
          public partial class Binding(uint id) : Attribute;

          [AttributeUsage(AttributeTargets.Field | AttributeTargets.Property)]
          public partial class BindingMode(BindingType access) : Attribute;

          public enum BindingType
          {
              [global::System.ObsoleteAttribute]
              Undefined,

              // BufferBindingType
              Uniform,
              Storage,
              ReadOnlyStorage,
              
              // SamplerBindingType
              Filtering,
              NonFiltering,
              Comparison,
              
              // textures, do not use this
              [global::System.ObsoleteAttribute]
              Texture,
          }
          #pragma warning restore CS9113
          """;

    private const string BindGroupLayout = "global::Silk.NET.WebGPU.Safe.BindGroupLayoutPtr";
    private const string BindGroup = "global::Silk.NET.WebGPU.Safe.BindGroupPtr";
    private const string Device = "global::Silk.NET.WebGPU.Safe.DevicePtr";
    private const string PipelineLayout = "global::Silk.NET.WebGPU.Safe.PipelineLayoutPtr";
    private const string VertexBufferLayout = "global::Silk.NET.WebGPU.Safe.VertexBufferLayout";
    private const string VertexStepMode = "VertexStepMode";
    private const string ColorTargetState = "global::Silk.NET.WebGPU.Safe.ColorTargetState";
    private const string VertexAttribute = "global::Silk.NET.WebGPU.VertexAttribute";
    private const string ShaderModuleHint = "global::Silk.NET.WebGPU.Safe.ShaderModuleCompilationHint";

    private const string CreateLayoutEntries = "global::Silk.NET.WebGPU.Safe.BindGroupLayoutEntries";
    private const string BindGroupEntries = "global::Silk.NET.WebGPU.Safe.BindGroupEntries";

    private readonly SyntaxToken[] _modifiers = [Token(SyntaxKind.PublicKeyword) /*, Token(SyntaxKind.StaticKeyword)*/];

    private SyntaxList<AttributeListSyntax> DefaultAttributeList =
    [
        AttributeList(
        [
            Attribute(ParseName("System.Runtime.CompilerServices.MethodImpl"))
                .WithArgumentList(AttributeArgumentList(
                    SeparatedList(new[]
                    {
                        AttributeArgument(
                            ParseExpression("System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining"))
                    }))),
            // compiler generated attribute
            Attribute(ParseName("System.Runtime.CompilerServices.CompilerGeneratedAttribute"))
        ])
    ];

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx => ctx.AddSource(
            "Attributes.g.cs",
            SourceText.From(AttributeSourceCode, Encoding.UTF8)));

        var provider = context.SyntaxProvider
            .CreateSyntaxProvider(
                (s, _) => s is ClassDeclarationSyntax,
                (ctx, _) => GetClassDeclarationForSourceGen(ctx))
            .Where(t => t.attributeFound)
            .Select((t, _) => t.Item1);

        context.RegisterSourceOutput(context.CompilationProvider.Combine(provider.Collect()),
            (ctx, t) => GenerateCode(ctx, t.Left, t.Right));
    }

    /// <summary>
    /// Checks whether the Node is annotated with the [Report] attribute and maps syntax context to the specific node type (ClassDeclarationSyntax).
    /// </summary>
    /// <param name="context">Syntax context, based on CreateSyntaxProvider predicate</param>
    /// <returns>The specific cast and whether the attribute was found.</returns>
    private static (ClassDeclarationSyntax, bool attributeFound) GetClassDeclarationForSourceGen(
        GeneratorSyntaxContext context)
    {
        var classDeclarationSyntax = (ClassDeclarationSyntax)context.Node;

        // Go through all attributes of the class.
        foreach (var attributeListSyntax in classDeclarationSyntax.AttributeLists)
        foreach (var attributeSyntax in attributeListSyntax.Attributes)
        {
            if (ModelExtensions.GetSymbolInfo(context.SemanticModel, attributeSyntax).Symbol is not IMethodSymbol
                attributeSymbol)
                continue; // if we can't get the symbol, ignore it

            var attributeName = attributeSymbol.ContainingType.ToDisplayString();

            // Check the full name of the [Report] attribute.
            if (attributeName == $"{Namespace}.{AttributeName}")
                return (classDeclarationSyntax, true);
        }

        return (classDeclarationSyntax, false);
    }

    /// <summary>
    /// Generate code action.
    /// It will be executed on specific nodes (ClassDeclarationSyntax annotated with the [Report] attribute) changed by the user.
    /// </summary>
    /// <param name="context">Source generation context used to add source files.</param>
    /// <param name="compilation">Compilation used to provide access to the Semantic Model.</param>
    /// <param name="classDeclarations">Nodes annotated with the [Report] attribute that trigger the generate action.</param>
    private void GenerateCode(SourceProductionContext context, Compilation compilation,
        ImmutableArray<ClassDeclarationSyntax> classDeclarations)
    {
        foreach (var classDeclarationSyntax in classDeclarations)
        {
            var wgslVisitor = new WgslVisitor(context, compilation, classDeclarationSyntax);
            classDeclarationSyntax.Accept(wgslVisitor);
            var shaderSource = $""""
                                """
                                {wgslVisitor.GetResult()}
                                """
                                """";

            // Get binding information
            var bindGroups = wgslVisitor.GetBindingGroups();
            var inAttributes = wgslVisitor.GetInputAttributes();
            var outAttribute = wgslVisitor.GetOutputAttribute();
            var entryPoints = wgslVisitor.GetEntryPoints();
            var structAttributes = wgslVisitor.GetStructAttributes();
            var generatedStructs = wgslVisitor.GetGeneratedStructs();
            var warnings = wgslVisitor.GetWarnings();

            // Generate a partial class with a ShaderSource constant
            var className = classDeclarationSyntax.Identifier.Text;

            // Get namespace from semantic model
            var semanticModel = compilation.GetSemanticModel(classDeclarationSyntax.SyntaxTree);
            var symbol = ModelExtensions.GetDeclaredSymbol(semanticModel, classDeclarationSyntax);
            var namespaceName = symbol!.ContainingNamespace.ToDisplayString();

            var interfaceMembers = new List<MemberDeclarationSyntax>();

            // Generate bind layout properties and methods
            var members = new List<MemberDeclarationSyntax>();

            // Generate shader entry points method
            members.AddRange(GenerateGetShaderEntryPointPorps(entryPoints));
            interfaceMembers.AddRange(GenerateGetShaderEntryPointPorps(entryPoints, true));

            // Add layout properties for each bind group
            foreach (var group in bindGroups)
            {
                // Generate bind group layout method
                members.Add(GenerateBindGroupLayoutMethod(group.Key, group.Value, className));
                interfaceMembers.Add(GenerateBindGroupLayoutMethod(group.Key, group.Value, className, true));

                // Generate bind group method
                members.Add(GenerateCreateBindGroupMethod(group.Key, group.Value, className));
                interfaceMembers.Add(GenerateCreateBindGroupMethod(group.Key, group.Value, className, true));
            }

            // Generate buffer layout methods
            if (inAttributes.Any())
            {
                members.Add(GenerateVertexBufferLayoutMethods(inAttributes));
                interfaceMembers.Add(GenerateVertexBufferLayoutMethods(inAttributes, true));
            }

            if (outAttribute is not null)
            {
                members.Add(GenerateOutLayoutMethod(outAttribute));
                interfaceMembers.Add(GenerateOutLayoutMethod(outAttribute, true));
            }

            // Generate pipeline layout method
            members.Add(GenerateGetPipelineLayoutMethod(bindGroups.Keys.OrderBy(k => k), className));
            interfaceMembers.Add(GenerateGetPipelineLayoutMethod(bindGroups.Keys.OrderBy(k => k), className, true));

            // Generate create shader module method
            members.Add(GenerateCreateShaderModuleMethod(className, entryPoints));
            interfaceMembers.Add(GenerateCreateShaderModuleMethod(className, entryPoints, true));

            // Using compilation unit to build the partial class
            var baseClass = CompilationUnit()
                .AddUsings(
                    UsingDirective(ParseName("System")),
                    UsingDirective(ParseName("System.Collections.Generic")),
                    UsingDirective(ParseName("System.Runtime.InteropServices")),
                    UsingDirective(ParseName("System.Runtime.CompilerServices")),
                    UsingDirective(ParseName("System.Numerics")),
                    UsingDirective(ParseName("GlmSharp")),
                    UsingDirective(ParseName("Silk.NET.WebGPU")),
                    UsingDirective(ParseName("Silk.NET.WebGPU.Safe"))
                )
                .AddMembers(FileScopedNamespaceDeclaration(ParseName(namespaceName)));

            var partialClass = baseClass.AddMembers(ClassDeclaration(className)
                .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.PartialKeyword))
                .WithBaseList(BaseList([SimpleBaseType(ParseName($"I{className}"))]))
                .AddMembers(CreatePropWithValue(ShaderSource,
                    LiteralExpression(SyntaxKind.StringLiteralExpression, Literal(shaderSource, shaderSource))))
                .AddMembers(members.ToArray())
                .AddMembers(generatedStructs.ToArray()));

            var interfaceClass = baseClass.AddMembers(
                InterfaceDeclaration($"I{className}")
                    .WithBaseList(BaseList([SimpleBaseType(ParseName("IWgslShader"))]))
                    .AddModifiers(Token(SyntaxKind.PublicKeyword))
                    .AddMembers(interfaceMembers.ToArray())
            );

            context.AddSource($"I{className}.g.cs",
                SourceText.From(interfaceClass.NormalizeWhitespace().ToFullString(), Encoding.UTF8));

            context.AddSource($"{className}.g.cs",
                SourceText.From(partialClass.NormalizeWhitespace().ToFullString(), Encoding.UTF8));
        }
    }

    private MemberDeclarationSyntax GenerateBindGroupLayoutMethod(uint groupId, BindGroupInfo bindGroup,
        string className, bool isInterface = false)
    {
        // Method signature: public BindGroupLayout CreateBindGroupLayout{groupId}(Device device, ...)
        var methodName = $"CreateBindGroupLayout{groupId}";
        var methodDeclaration = MethodDeclaration(
                ParseTypeName(BindGroupLayout),
                methodName
            ).AddModifiers(_modifiers)
            .WithAttributeLists(DefaultAttributeList);

        // Add parameters for customizable options
        var parameters = new List<ParameterSyntax>
        {
            Parameter(Identifier("device"))
                .WithType(ParseTypeName(Device))
        };

        // Add specific parameters for each binding entry
        foreach (var entry in bindGroup.Entries)
        {
            switch (entry.BindingType)
            {
                case BindingType.Uniform or BindingType.ReadOnlyStorage or BindingType.Storage:
                    // Add hasDynamicOffset parameter for buffers
                    parameters.Add(Parameter(Identifier($"{entry.Name}HasDynamicOffset"))
                        .WithType(ParseTypeName("bool"))
                        .WithDefault(EqualsValueClause(ParseExpression("false"))));
                    break;
                case BindingType.Texture:
                {
                    // Add multisampled parameter for textures
                    parameters.Add(Parameter(Identifier($"{entry.Name}Multisampled"))
                        .WithType(ParseTypeName("bool"))
                        .WithDefault(EqualsValueClause(ParseExpression("false"))));

                    // Add viewDimension - determine default from type name
                    var defaultDimension = "TextureViewDimension.Dimension2D"; // Default to 2D
                    if (entry.TypeName.Contains("3d"))
                        defaultDimension = "TextureViewDimension.Dimension3D";
                    else if (entry.TypeName.Contains("1d"))
                        defaultDimension = "TextureViewDimension.Dimension1D";
                    else if (entry.TypeName.Contains("2d_array"))
                        defaultDimension = "TextureViewDimension.Dimension2DArray";
                    else if (entry.TypeName.Contains("cube_array"))
                        defaultDimension = "TextureViewDimension.DimensionCubeArray";
                    else if (entry.TypeName.Contains("cube"))
                        defaultDimension = "TextureViewDimension.DimensionCube";

                    parameters.Add(Parameter(Identifier($"{entry.Name}ViewDimension"))
                        .WithType(ParseTypeName("TextureViewDimension"))
                        .WithDefault(EqualsValueClause(ParseExpression(defaultDimension))));
                    break;
                }
                case BindingType.Filtering or BindingType.NonFiltering or BindingType.Comparison:
                    // there are none! throw new NotImplementedException("Sry I haven't implemented Samplers");
                    break;
            }
        }

        // optional parameters with default values
        foreach (var entry in bindGroup.Entries)
        {
            if (entry.BindingType is not (BindingType.Uniform or BindingType.ReadOnlyStorage or BindingType.Storage))
                continue;
            // Add minSize parameter for buffers
            parameters.Add(Parameter(Identifier($"{entry.Name}MinSize"))
                .WithType(ParseTypeName("ulong?"))
                .WithDefault(EqualsValueClause(ParseExpression("null"))));
        }

        // Add label parameter
        parameters.Add(Parameter(Identifier("label"))
            .WithType(ParseTypeName("string"))
            .WithDefault(EqualsValueClause(ParseExpression($"\"{className}::BindGroupLayout_{groupId}\""))));

        methodDeclaration = methodDeclaration.WithParameterList(ParameterList(SeparatedList(parameters)));

        if (isInterface)
            return methodDeclaration.WithSemicolonToken(Token(SyntaxKind.SemicolonToken));

        // Create entries array
        var entries = new List<string>();
        foreach (var entry in bindGroup.Entries)
        {
            var shaderStage = "ShaderStage.Vertex | ShaderStage.Fragment | ShaderStage.Compute";
            var entryCode = entry.BindingType switch
            {
                BindingType.Storage or BindingType.ReadOnlyStorage or BindingType.Uniform =>
                    $"{CreateLayoutEntries}.Buffer({entry.Binding}, {shaderStage}, " +
                    $"BufferBindingType.{entry.BindingType}, {entry.Name}MinSize ?? (ulong)Marshal.SizeOf<{entry.TypeName}>(), {entry.Name}HasDynamicOffset)",
                BindingType.Filtering or BindingType.NonFiltering or BindingType.Comparison =>
                    $"{CreateLayoutEntries}.Sampler({entry.Binding}, {shaderStage}, SamplerBindingType.{entry.BindingType})",
                BindingType.Texture =>
                    $"{CreateLayoutEntries}.Texture({entry.Binding}, {shaderStage}, TextureSampleType.{entry.TextureFormat}, " +
                    $"{entry.Name}ViewDimension, {entry.Name}Multisampled)",
                _ => throw new NotImplementedException($"Binding type {entry.BindingType} not implemented")
            };

            entries.Add(entryCode);
        }

        var entriesArray = $"[{string.Join(",\r\n", entries)}]";
        return methodDeclaration.WithBody(
            Block(ReturnStatement(ParseExpression($"device.CreateBindGroupLayout({entriesArray}, label: label)"))));
    }

    private MemberDeclarationSyntax GenerateCreateBindGroupMethod(uint groupId, BindGroupInfo bindGroup,
        string className, bool isInterface = false)
    {
        // Method signature: public BindGroup CreateBindGroup{groupId}(Device device, ...)
        var methodName = $"CreateBindGroup{groupId}";
        var methodDeclaration = MethodDeclaration(
                ParseTypeName(BindGroup),
                methodName
            ).AddModifiers(_modifiers)
            .WithAttributeLists(DefaultAttributeList);

        // Add parameters
        var parameters = new List<ParameterSyntax>
        {
            Parameter(Identifier("device"))
                .WithType(ParseTypeName(Device)),
            Parameter(Identifier("layout"))
                .WithType(ParseTypeName(BindGroupLayout))
        };

        // Add required parameters first (without default values)
        foreach (var entry in bindGroup.Entries)
        {
            switch (entry.BindingType)
            {
                case BindingType.Uniform or BindingType.ReadOnlyStorage or BindingType.Storage:
                    parameters.Add(Parameter(Identifier($"{entry.Name}Buffer"))
                        .WithType(ParseTypeName("BufferPtr")));
                    break;

                case BindingType.Filtering or BindingType.NonFiltering or BindingType.Comparison:
                    parameters.Add(Parameter(Identifier(entry.Name))
                        .WithType(ParseTypeName("SamplerPtr")));
                    break;

                case BindingType.Texture:
                    parameters.Add(Parameter(Identifier($"{entry.Name}View"))
                        .WithType(ParseTypeName("TextureViewPtr")));
                    break;
            }
        }

        // Add optional parameters with default values after all required parameters
        foreach (var entry in bindGroup.Entries)
        {
            if (entry.BindingType is not (BindingType.Uniform or BindingType.ReadOnlyStorage or BindingType.Storage))
                continue;
            // Add offset and size parameters for buffers
            parameters.Add(Parameter(Identifier($"{entry.Name}Offset"))
                .WithType(ParseTypeName("ulong"))
                .WithDefault(EqualsValueClause(ParseExpression("0"))));
            parameters.Add(Parameter(Identifier($"{entry.Name}Size"))
                .WithType(ParseTypeName("ulong?"))
                .WithDefault(EqualsValueClause(ParseExpression("null"))));
        }

        // Add label parameter
        parameters.Add(Parameter(Identifier("label"))
            .WithType(ParseTypeName("string"))
            .WithDefault(EqualsValueClause(ParseExpression($"\"{className}::BindGroup_{groupId}\""))));

        methodDeclaration = methodDeclaration.WithParameterList(ParameterList(SeparatedList(parameters)));

        if (isInterface)
            return methodDeclaration.WithSemicolonToken(Token(SyntaxKind.SemicolonToken));

        // Create bindGroup entries
        var entries = new List<string>();
        foreach (var entry in bindGroup.Entries)
        {
            var entryCode = entry.BindingType switch
            {
                BindingType.Uniform or BindingType.Storage or BindingType.ReadOnlyStorage =>
                    $"{BindGroupEntries}.Buffer({entry.Binding}, {entry.Name}Buffer, {entry.Name}Offset, {entry.Name}Size ?? (ulong)Marshal.SizeOf<{entry.TypeName}>())",

                BindingType.Filtering or BindingType.NonFiltering or BindingType.Comparison =>
                    $"{BindGroupEntries}.Sampler({entry.Binding}, {entry.Name})",

                BindingType.Texture =>
                    $"{BindGroupEntries}.Texture({entry.Binding}, {entry.Name}View)",

                _ => throw new NotImplementedException($"Binding type {entry.BindingType} not implemented")
            };

            entries.Add(entryCode);
        }

        var entriesArray = $"[{string.Join(",\r\n", entries)}]";

        return methodDeclaration.WithBody(Block(
            ReturnStatement(ParseExpression($"device.CreateBindGroup(layout, {entriesArray}, label: label)"))));
    }

    private MemberDeclarationSyntax GenerateVertexBufferLayoutMethods(
        IReadOnlyList<IReadOnlyList<VertexAttributeInfo>> vertexAttributes, bool isInterface = false)
    {
        // Method signature: public VertexBufferLayout[] GetVertexBufferLayout()
        var methodDeclaration = MethodDeclaration(
                ArrayType(ParseTypeName(VertexBufferLayout), [ArrayRankSpecifier()]),
                "GetVertexBufferLayout"
            ).AddModifiers(_modifiers)
            .WithParameterList(ParameterList(SeparatedList(vertexAttributes.Select(vertexAttributeInfos =>
                Parameter(Identifier(vertexAttributeInfos[0].StructName.ToCamelCase()))
                    .WithType(ParseTypeName(VertexStepMode))))))
            .WithAttributeLists(DefaultAttributeList);

        if (isInterface)
            return methodDeclaration.WithSemicolonToken(Token(SyntaxKind.SemicolonToken));

        List<string> body = [];
        foreach (var vertexAttributeInfos in vertexAttributes)
        {
            var vertexAttributesCode = new List<string>();
            string structName = "";
            foreach (var attr in vertexAttributeInfos)
            {
                structName = attr.StructName;
                var formatName = GetVertexFormatName(attr.VertexFormat);
                vertexAttributesCode.Add(
                    $"new {VertexAttribute}(VertexFormat.{formatName}, offset: (uint)Marshal.OffsetOf<{structName}>(nameof({structName}.{attr.Name})), shaderLocation: {attr.Location})");
            }

            body.Add(
                $"new {VertexBufferLayout}((uint)Marshal.SizeOf<{structName}>(), {structName.ToCamelCase()}, " +
                $"[{string.Join(",\r\n", vertexAttributesCode)}])");
        }

        return methodDeclaration.WithBody(Block(ReturnStatement(ParseExpression($"[{string.Join(",\r\n", body)}]"))));
    }

    private MemberDeclarationSyntax GenerateOutLayoutMethod(
        IReadOnlyList<VertexAttributeInfo> instanceAttributes, bool isInterface = false)
    {
        // Method signature: public T[] ColorTarget()
        var parameters = new List<ParameterSyntax>();

        // add each instance attribute as a parameter
        foreach (var vertexAttributeInfose in instanceAttributes)
        {
            parameters.Add(Parameter(Identifier(vertexAttributeInfose.Name.ToCamelCase()))
                .WithType(IdentifierName("T")));
        }

        var methodDeclaration = MethodDeclaration(
                ArrayType(IdentifierName("T"), [ArrayRankSpecifier()]),
                "ColorTarget")
            .AddModifiers(_modifiers)
            .WithTypeParameterList(TypeParameterList([TypeParameter("T")]))
            .WithAttributeLists(DefaultAttributeList)
            .WithParameterList(ParameterList(SeparatedList(parameters)));

        if (isInterface)
            return methodDeclaration.WithSemicolonToken(Token(SyntaxKind.SemicolonToken));


        return methodDeclaration.WithBody(Block(ReturnStatement(
            ParseExpression($" [{string.Join(",\r\n", parameters.Select(a => $"{a.Identifier.Text}"))}]"))));
    }


    private MemberDeclarationSyntax GenerateGetPipelineLayoutMethod(IEnumerable<uint> groupIds, string className,
        bool isInterface = false)
    {
        // Method signature: public PipelineLayout CreatePipelineLayout(Device device, string label = null)
        // Add parameters
        var parameters = new List<ParameterSyntax>
        {
            Parameter(Identifier("device"))
                .WithType(ParseTypeName(Device))
        };

        // layout for group bind layouts
        var parameterNames = new List<string>();
        foreach (var groupId in groupIds)
        {
            var paramName = $"bindGroupLayout{groupId}";
            parameterNames.Add(paramName);
            parameters.Add(Parameter(Identifier(paramName))
                .WithType(ParseTypeName(BindGroupLayout)));
        }

        parameters.Add(Parameter(Identifier("label"))
            .WithType(ParseTypeName("string"))
            .WithDefault(EqualsValueClause(ParseExpression($"\"{className}::PipelineLayout\""))));

        var methodDeclaration = MethodDeclaration(
                ParseTypeName(PipelineLayout),
                "CreatePipelineLayout"
            ).AddModifiers(_modifiers)
            .WithAttributeLists(DefaultAttributeList)
            .WithParameterList(ParameterList(SeparatedList(parameters)));


        if (isInterface)
            return methodDeclaration.WithSemicolonToken(Token(SyntaxKind.SemicolonToken));

        // Create array of layouts
        var layoutsArray = string.Join(",\r\n", parameterNames);
        return methodDeclaration.WithBody(
            Block(ReturnStatement(ParseExpression($"device.CreatePipelineLayout([{layoutsArray}], label: label)"))));
    }

    private IEnumerable<MemberDeclarationSyntax> GenerateGetShaderEntryPointPorps(ShaderEntryInfo entryPoints,
        bool isInterface = false)
    {
        // public string VertexEntryPoint { get; }
        // public string FragmentEntryPoint { get; }

        if (entryPoints.Vertex?.EntryPoint is not null)
            yield return CreatePropWithValue("VertexEntryPoint",
                LiteralExpression(SyntaxKind.StringLiteralExpression, Literal(entryPoints.Vertex?.EntryPoint)));

        if (entryPoints.Fragment?.EntryPoint is not null)
            yield return CreatePropWithValue("FragmentEntryPoint",
                LiteralExpression(SyntaxKind.StringLiteralExpression, Literal(entryPoints.Fragment?.EntryPoint)));

        if (entryPoints.Compute?.EntryPoint is not null)
            yield return CreatePropWithValue("ComputeEntryPoint",
                LiteralExpression(SyntaxKind.StringLiteralExpression, Literal(entryPoints.Compute?.EntryPoint)));
    }

    private static PropertyDeclarationSyntax CreatePropWithValue(string name, ExpressionSyntax value)
    {
        return PropertyDeclaration(ParseTypeName("string"), name)
            .WithExpressionBody(ArrowExpressionClause(value))
            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken))
            .AddModifiers(Token(SyntaxKind.PublicKeyword));
    }

    private MemberDeclarationSyntax GenerateCreateShaderModuleMethod(string className, ShaderEntryInfo entryPoints,
        bool isInterface = false)
    {
        // Method signature: public ShaderModulePtr CreateShaderModule(Device device)

        var methodDeclaration = MethodDeclaration(
                ParseTypeName("ShaderModulePtr"),
                "CreateShaderModule"
            ).AddModifiers(_modifiers)
            .WithAttributeLists(DefaultAttributeList);

        // Add parameters
        var parameters = new List<ParameterSyntax>
        {
            Parameter(Identifier("device"))
                .WithType(ParseTypeName(Device)),
            Parameter(Identifier("pipelineLayout"))
                .WithType(ParseTypeName(PipelineLayout)),
            Parameter(Identifier("label"))
                .WithType(ParseTypeName("string"))
                .WithDefault(EqualsValueClause(ParseExpression($"\"{className}::ShaderModule\"")))
        };

        methodDeclaration = methodDeclaration.WithParameterList(ParameterList(SeparatedList(parameters)));

        if (isInterface)
            return methodDeclaration.WithSemicolonToken(Token(SyntaxKind.SemicolonToken));

        return methodDeclaration.WithBody(
            Block(ReturnStatement(ParseExpression(
                $"""
                 device.CreateShaderModuleWGSL({ShaderSource}, [{(entryPoints.Fragment?.EntryPoint != null
                     ? $"new {ShaderModuleHint}(\"{entryPoints.Fragment?.EntryPoint}\", pipelineLayout), "
                     : "")}{(entryPoints.Vertex?.EntryPoint != null
                     ? $"new {ShaderModuleHint}(\"{entryPoints.Vertex?.EntryPoint}\", pipelineLayout), "
                     : "")}{(entryPoints.Compute?.EntryPoint != null
                     ? $"new {ShaderModuleHint}(\"{entryPoints.Compute?.EntryPoint}\", pipelineLayout)"
                     : "")}], label: label)
                 """))));
    }

    private string GetVertexFormatName(VertexFormat format)
    {
        return format.ToString();
    }
}
