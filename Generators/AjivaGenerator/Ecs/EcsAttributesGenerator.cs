using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AjivaGenerator.Ecs;

/// <summary>
/// Generates the ECS component attributes and enums
/// </summary>
public static class EcsAttributesGenerator
{
    public static void GenerateAttributes(IncrementalGeneratorPostInitializationContext context)
    {
        var sourceCode = GenerateAttributeSourceCode();
        context.AddSource("EcsAttributes.g.cs", SourceText.From(sourceCode, Encoding.UTF8));
    }

    private static string GenerateAttributeSourceCode()
    {
        return """
            // <auto-generated/>
            using System;

            namespace Common.EcsV2.Generator;

            /// <summary>
            /// Defines where a component can exist
            /// </summary>
            [Flags]
            public enum ComponentScope
            {
                /// <summary>Server only - not available on client</summary>
                Server = 1 << 0,
                
                /// <summary>Client only - not available on server</summary>
                Client = 1 << 1,
                
                /// <summary>Available on both server and client</summary>
                Shared = Server | Client,
            }

            /// <summary>
            /// Defines how a component synchronizes over the network
            /// </summary>
            [Flags] 
            public enum ComponentSync
            {
                /// <summary>No network synchronization</summary>
                None = 0,
                
                /// <summary>Server sends updates to clients (server authoritative)</summary>
                ServerToClient = 1 << 0,
                
                /// <summary>Client sends updates to server (player input only)</summary>
                ClientToServer = 1 << 1,
                
                /// <summary>Bidirectional sync (use with caution)</summary>
                Bidirectional = ServerToClient | ClientToServer,
            }

            /// <summary>
            /// Storage and behavior flags for components
            /// </summary>
            [Flags]
            public enum ComponentFlags
            {
                None = 0,
                
                /// <summary>Dense array storage - best for common components</summary>
                Dense = 1 << 0,
                
                /// <summary>Sparse dictionary storage - best for rare components</summary>
                Sparse = 1 << 1,
                
                /// <summary>Track component changes for network sync</summary>
                DirtyTracked = 1 << 2,
                
                /// <summary>Send network updates immediately when changed</summary>
                ImmediateSync = 1 << 3,
                
                /// <summary>Use reliable network delivery</summary>
                ReliableSync = 1 << 4,
                
                /// <summary>Use unreliable network delivery (faster)</summary>
                UnreliableSync = 1 << 5,
                
                /// <summary>Sync only once when component is added</summary>
                SyncOnce = 1 << 6,
            }

            /// <summary>
            /// Marks a struct as an ECS component with specified scope, sync, and storage behavior
            /// </summary>
            [AttributeUsage(AttributeTargets.Struct)]
            public class EcsComponentAttribute : Attribute
            {
                public ComponentScope Scope { get; }
                public ComponentSync Sync { get; }
                public ComponentFlags Flags { get; }
                
                public EcsComponentAttribute(ComponentScope scope, ComponentSync sync, ComponentFlags flags)
                {
                    Scope = scope;
                    Sync = sync;
                    Flags = flags;
                }
            }
            """;
    }
}
