using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AjivaGenerator.Ecs;

/// <summary>
/// Generates the main EcsWorld class with component storage and methods
/// </summary>
internal static class EcsWorldGenerator
{
    public static void GenerateEcsWorld(SourceProductionContext context, ImmutableArray<ComponentInfo> components,
        string className)
    {
        var sourceCode = BuildEcsWorldClass(components, className);
        context.AddSource($"{className}.g.cs", SourceText.From(sourceCode, Encoding.UTF8));
    }

    private static string BuildEcsWorldClass(ImmutableArray<ComponentInfo> components, string className)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using Ajiva.Ecs;");
        sb.AppendLine("using Common.Ecs;");
        sb.AppendLine();
        sb.AppendLine("namespace Ajiva.Ecs;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine(
            $"/// Generated ECS World containing all component storage and entity management for {className}");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("[System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        sb.AppendLine("[System.Runtime.CompilerServices.CompilerGenerated]");
        sb.AppendLine($"public partial class {className}");
        sb.AppendLine("{");

        // Entity management
        GenerateEntityManagement(sb);

        // Component storage and methods for each component
        foreach (var component in components)
        {
            GenerateComponentStorage(sb, component);
            GenerateComponentMethods(sb, component);
        }

        // Universal component methods
        GenerateUniversalMethods(sb, components);

        // Query methods
        GenerateQueryMethods(sb, components);

        // Sync methods for networked components
        GenerateSyncMethods(sb, components);

        // Helper methods
        GenerateHelperMethods(sb, components);

        sb.AppendLine("}");

        return sb.ToString();
    }

    private static void GenerateEntityManagement(StringBuilder sb)
    {
        sb.Append("""
                          private int _nextEntityId = 1;
                          private readonly Stack<int> _freeEntityIds = new();
                       
                          /// <summary>Creates a new entity and returns its ID</summary>
                          public EntityId CreateEntity()
                          {
                              var id = _freeEntityIds.Count > 0
                                  ? _freeEntityIds.Pop()
                                  : _nextEntityId++;
                              return new EntityId(id);
                          }
                       
                          /// <summary>Deletes an entity and removes all its components</summary>
                          public void DeleteEntity(EntityId id)
                          {
                              _freeEntityIds.Push(id.Value);
                              
                              // Remove from all component stores
                              RemoveAllComponents(id);
                          }
                  """);
    }

    private static void GenerateComponentStorage(StringBuilder sb, ComponentInfo component)
    {
        sb.AppendLine($"    // #region {component.Name} Storage");
        sb.AppendLine();

        if (component.Flags.HasFlag(ComponentFlags.Dense))
        {
            sb.AppendLine($"    private {component.Name}[] _data_{component.Name} = new {component.Name}[1024];");
            sb.AppendLine($"    private BitArray _set_{component.Name} = new(1024);");

            if (component.Flags.HasFlag(ComponentFlags.DirtyTracked))
            {
                sb.AppendLine($"    private BitArray _dirty_{component.Name} = new(1024);");
            }
        }
        else // Sparse
        {
            sb.AppendLine($"    private readonly Dictionary<int, {component.Name}> _data_{component.Name} = new();");
            sb.AppendLine($"    private readonly HashSet<int> _set_{component.Name} = new();");

            if (component.Flags.HasFlag(ComponentFlags.DirtyTracked))
            {
                sb.AppendLine($"    private readonly HashSet<int> _dirty_{component.Name} = new();");
            }
        }

        sb.AppendLine();
    }

    private static void GenerateComponentMethods(StringBuilder sb, ComponentInfo component)
    {
        var name = component.Name;

        sb.AppendLine($"    // #region {name} Methods");
        sb.AppendLine();

        // Add method
        sb.AppendLine($"    /// <summary>Adds a {name} component to the entity</summary>");
        sb.AppendLine($"    public void Add{name}(EntityId id, in {name} value)");
        sb.AppendLine("    {");

        if (component.Flags.HasFlag(ComponentFlags.Dense))
        {
            sb.AppendLine("        EnsureCapacity(id.Value);");
            sb.AppendLine($"        _data_{name}[id.Value] = value;");
            sb.AppendLine($"        _set_{name}[id.Value] = true;");

            if (component.Flags.HasFlag(ComponentFlags.DirtyTracked))
            {
                sb.AppendLine($"        _dirty_{name}[id.Value] = true;");
            }
        }
        else // Sparse
        {
            sb.AppendLine($"        _data_{name}[id.Value] = value;");
            sb.AppendLine($"        _set_{name}.Add(id.Value);");

            if (component.Flags.HasFlag(ComponentFlags.DirtyTracked))
            {
                sb.AppendLine($"        _dirty_{name}.Add(id.Value);");
            }
        }

        if (component.Flags.HasFlag(ComponentFlags.ImmediateSync))
        {
            sb.AppendLine($"        // TODO: Immediate sync for {name}");
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        // Remove method
        sb.AppendLine($"    /// <summary>Removes the {name} component from the entity</summary>");
        sb.AppendLine($"    public void Remove{name}(EntityId id)");
        sb.AppendLine("    {");

        if (component.Flags.HasFlag(ComponentFlags.Dense))
        {
            sb.AppendLine($"        if (id.Value < _set_{name}.Length)");
            sb.AppendLine("        {");
            sb.AppendLine($"            _set_{name}[id.Value] = false;");
            sb.AppendLine($"            _data_{name}[id.Value] = default;");

            if (component.Flags.HasFlag(ComponentFlags.DirtyTracked))
            {
                sb.AppendLine($"            _dirty_{name}[id.Value] = false;");
            }

            sb.AppendLine("        }");
        }
        else // Sparse
        {
            sb.AppendLine($"        _data_{name}.Remove(id.Value);");
            sb.AppendLine($"        _set_{name}.Remove(id.Value);");

            if (component.Flags.HasFlag(ComponentFlags.DirtyTracked))
            {
                sb.AppendLine($"        _dirty_{name}.Remove(id.Value);");
            }
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        // Has method
        sb.AppendLine($"    /// <summary>Checks if the entity has a {name} component</summary>");
        sb.AppendLine($"    public bool Has{name}(EntityId id)");
        sb.AppendLine("    {");

        if (component.Flags.HasFlag(ComponentFlags.Dense))
        {
            sb.AppendLine($"        return id.Value < _set_{name}.Length && _set_{name}[id.Value];");
        }
        else // Sparse
        {
            sb.AppendLine($"        return _set_{name}.Contains(id.Value);");
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        // Get method (only for dense components to allow ref returns)
        if (component.Flags.HasFlag(ComponentFlags.Dense))
        {
            sb.AppendLine($"    /// <summary>Gets the {name} component value (dense only)</summary>");
            sb.AppendLine($"    public {name} Get{name}(EntityId id)");
            sb.AppendLine("    {");
            sb.AppendLine($"        if (!Has{name}(id))");
            sb.AppendLine(
                $"            throw new InvalidOperationException($\"Entity {{id}} does not have {name} component\");");
            sb.AppendLine($"        return _data_{name}[id.Value];");
            sb.AppendLine("    }");
            sb.AppendLine();

            sb.AppendLine($"    /// <summary>Gets a reference to the {name} component for updating (dense only)</summary>");
            sb.AppendLine($"    public ref {name} Update{name}(EntityId id)");
            sb.AppendLine("    {");
            sb.AppendLine($"        if (!Has{name}(id))");
            sb.AppendLine(
                $"            throw new InvalidOperationException($\"Entity {{id}} does not have {name} component\");");

            if (component.Flags.HasFlag(ComponentFlags.DirtyTracked))
            {
                sb.AppendLine($"        _dirty_{name}[id.Value] = true;");
            }

            sb.AppendLine($"        return ref _data_{name}[id.Value];");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        // TryGet method
        sb.AppendLine($"    /// <summary>Tries to get the {name} component value</summary>");
        sb.AppendLine($"    public bool TryGet{name}(EntityId id, out {name} value)");
        sb.AppendLine("    {");

        if (component.Flags.HasFlag(ComponentFlags.Dense))
        {
            sb.AppendLine($"        if (Has{name}(id))");
            sb.AppendLine("        {");
            sb.AppendLine($"            value = _data_{name}[id.Value];");
            sb.AppendLine("            return true;");
            sb.AppendLine("        }");
        }
        else // Sparse
        {
            sb.AppendLine($"        return _data_{name}.TryGetValue(id.Value, out value);");
        }

        sb.AppendLine("        value = default;");
        sb.AppendLine("        return false;");
        sb.AppendLine("    }");
        sb.AppendLine();

        // GetEntitiesWith method
        sb.AppendLine($"    /// <summary>Gets all entities that have the {name} component</summary>");
        sb.AppendLine($"    public IEnumerable<EntityId> GetEntitiesWith{name}()");
        sb.AppendLine("    {");

        if (component.Flags.HasFlag(ComponentFlags.Dense))
        {
            sb.AppendLine($"        for (int i = 0; i < _set_{name}.Length; i++)");
            sb.AppendLine("        {");
            sb.AppendLine($"            if (_set_{name}[i])");
            sb.AppendLine("                yield return new EntityId(i);");
            sb.AppendLine("        }");
        }
        else // Sparse
        {
            sb.AppendLine($"        return _set_{name}.Select(id => new EntityId(id));");
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        // Dirty tracking methods
        if (component.Flags.HasFlag(ComponentFlags.DirtyTracked))
        {
            sb.AppendLine($"    /// <summary>Checks if the entity has the {name} component and it is dirty</summary>");
            sb.AppendLine($"    public bool HasDirty{name}(EntityId id)");
            sb.AppendLine("    {");

            if (component.Flags.HasFlag(ComponentFlags.Dense))
            {
                sb.AppendLine($"        return id.Value < _dirty_{name}.Length && _dirty_{name}[id.Value] && _set_{name}[id.Value];");
            }
            else // Sparse
            {
                sb.AppendLine($"        return _dirty_{name}.Contains(id.Value) && _set_{name}.Contains(id.Value);");
            }

            sb.AppendLine("    }");
            sb.AppendLine();

            sb.AppendLine($"    /// <summary>Marks the {name} component as dirty</summary>");
            sb.AppendLine($"    public void Mark{name}Dirty(EntityId id)");
            sb.AppendLine("    {");
            sb.AppendLine($"        if (Has{name}(id))");
            sb.AppendLine("        {");

            if (component.Flags.HasFlag(ComponentFlags.Dense))
            {
                sb.AppendLine("            EnsureCapacity(id.Value);");
                sb.AppendLine($"            _dirty_{name}[id.Value] = true;");
            }
            else // Sparse
            {
                sb.AppendLine($"            _dirty_{name}.Add(id.Value);");
            }

            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();

            sb.AppendLine($"    /// <summary>Gets all dirty {name} components</summary>");
            sb.AppendLine($"    public IEnumerable<(EntityId, {name})> GetDirty{name}()");
            sb.AppendLine("    {");

            if (component.Flags.HasFlag(ComponentFlags.Dense))
            {
                sb.AppendLine($"        for (int i = 0; i < _dirty_{name}.Length; i++)");
                sb.AppendLine("        {");
                sb.AppendLine($"            if (_dirty_{name}[i] && _set_{name}[i])");
                sb.AppendLine($"                yield return (new EntityId(i), _data_{name}[i]);");
                sb.AppendLine("        }");
            }
            else // Sparse
            {
                sb.AppendLine($"        foreach (var id in _dirty_{name})");
                sb.AppendLine("        {");
                sb.AppendLine($"            if (_data_{name}.TryGetValue(id, out var value))");
                sb.AppendLine("                yield return (new EntityId(id), value);");
                sb.AppendLine("        }");
            }

            sb.AppendLine("    }");
            sb.AppendLine();

            sb.AppendLine($"    /// <summary>Clears the dirty flag for {name} component</summary>");
            sb.AppendLine($"    public void Clear{name}Dirty(EntityId id)");
            sb.AppendLine("    {");
            sb.AppendLine($"        if (Has{name}(id))");
            sb.AppendLine("        {");

            if (component.Flags.HasFlag(ComponentFlags.Dense))
            {
                sb.AppendLine($"            if (id.Value < _dirty_{name}.Length)");
                sb.AppendLine($"                _dirty_{name}[id.Value] = false;");
            }
            else // Sparse
            {
                sb.AppendLine($"            _dirty_{name}.Remove(id.Value);");
            }

            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();

            sb.AppendLine($"    /// <summary>Clears all dirty flags for {name} components</summary>");
            sb.AppendLine($"    public void ClearAll{name}Dirty()");
            sb.AppendLine("    {");

            if (component.Flags.HasFlag(ComponentFlags.Dense))
            {
                sb.AppendLine($"        _dirty_{name}.SetAll(false);");
            }
            else // Sparse
            {
                sb.AppendLine($"        _dirty_{name}.Clear();");
            }

            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine();
    }

    private static void GenerateUniversalMethods(StringBuilder sb, ImmutableArray<ComponentInfo> components)
    {
        sb.AppendLine("    // #region Universal Component Methods");
        sb.AppendLine();

        // Has<T> method
        sb.AppendLine("    /// <summary>Checks if entity has component of type T</summary>");
        sb.AppendLine("    public bool Has<T>(EntityId id) where T : IComponent");
        sb.AppendLine("    {");
        sb.AppendLine("        return typeof(T) switch");
        sb.AppendLine("        {");

        foreach (var component in components)
        {
            sb.AppendLine($"            _ when typeof(T) == typeof({component.Name}) => Has{component.Name}(id),");
        }

        sb.AppendLine(
            "            _ => throw new NotSupportedException($\"Component type {typeof(T)} is not supported\")");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Remove<T> method
        sb.AppendLine("    /// <summary>Removes component of type T from entity</summary>");
        sb.AppendLine("    public void Remove<T>(EntityId id) where T : IComponent");
        sb.AppendLine("    {");
        sb.AppendLine("        switch (typeof(T))");
        sb.AppendLine("        {");

        foreach (var component in components)
        {
            sb.AppendLine($"            case var t when t == typeof({component.Name}):");
            sb.AppendLine($"                Remove{component.Name}(id);");
            sb.AppendLine("                break;");
        }

        sb.AppendLine("            default:");
        sb.AppendLine(
            "                throw new NotSupportedException($\"Component type {typeof(T)} is not supported\");");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine();
    }

    private static void GenerateQueryMethods(StringBuilder sb, ImmutableArray<ComponentInfo> components)
    {
        sb.AppendLine("    // #region Query Methods");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>Gets all entities with component type T</summary>");
        sb.AppendLine("    public IEnumerable<EntityId> GetEntitiesWith<T>() where T : IComponent");
        sb.AppendLine("    {");
        sb.AppendLine("        return typeof(T) switch");
        sb.AppendLine("        {");

        foreach (var component in components)
        {
            sb.AppendLine(
                $"            _ when typeof(T) == typeof({component.Name}) => GetEntitiesWith{component.Name}(),");
        }

        sb.AppendLine(
            "            _ => throw new NotSupportedException($\"Component type {typeof(T)} is not supported\")");
        sb.AppendLine("        };");
        sb.AppendLine("    }");

        sb.AppendLine();
    }

    private static void GenerateSyncMethods(StringBuilder sb, ImmutableArray<ComponentInfo> components)
    {
        var syncComponents = components
            .Where(c => c.Sync != ComponentSync.None && c.Flags.HasFlag(ComponentFlags.DirtyTracked)).ToArray();

        if (!syncComponents.Any()) return;

        sb.AppendLine("    // #region Network Sync Methods");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>Syncs all dirty components to network</summary>");
        sb.AppendLine("    public void SyncAllDirtyComponents()");
        sb.AppendLine("    {");

        foreach (var component in syncComponents)
        {
            sb.AppendLine($"        Sync{component.Name}Components();");
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        foreach (var component in syncComponents)
        {
            sb.AppendLine($"    /// <summary>Syncs dirty {component.Name} components</summary>");
            sb.AppendLine($"    private void Sync{component.Name}Components()");
            sb.AppendLine("    {");
            sb.AppendLine($"        foreach (var (entityId, component) in GetDirty{component.Name}())");
            sb.AppendLine("        {");
            sb.AppendLine($"            // TODO: Send {component.Name}SyncPacket");
            sb.AppendLine($"            Clear{component.Name}Dirty(entityId);");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine();
    }

    private static void GenerateHelperMethods(StringBuilder sb, ImmutableArray<ComponentInfo> components)
    {
        sb.AppendLine("    // #region Helper Methods");
        sb.AppendLine();

        // RemoveAllComponents method
        sb.AppendLine("    /// <summary>Removes all components from an entity</summary>");
        sb.AppendLine("    private void RemoveAllComponents(EntityId id)");
        sb.AppendLine("    {");

        foreach (var component in components)
        {
            sb.AppendLine($"        Remove{component.Name}(id);");
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        // EnsureCapacity method for dense components
        var denseComponents = components.Where(c => c.Flags.HasFlag(ComponentFlags.Dense)).ToArray();

        if (denseComponents.Any())
        {
            sb.AppendLine("    /// <summary>Ensures capacity for dense component arrays</summary>");
            sb.AppendLine("    private void EnsureCapacity(int entityId)");
            sb.AppendLine("    {");

            foreach (var component in denseComponents)
            {
                sb.AppendLine($"        if (entityId >= _data_{component.Name}.Length)");
                sb.AppendLine("        {");
                sb.AppendLine($"            var newSize = Math.Max(entityId + 1, _data_{component.Name}.Length * 2);");
                sb.AppendLine($"            Array.Resize(ref _data_{component.Name}, newSize);");
                sb.AppendLine($"            _set_{component.Name}.Length = newSize;");

                if (component.Flags.HasFlag(ComponentFlags.DirtyTracked))
                {
                    sb.AppendLine($"            _dirty_{component.Name}.Length = newSize;");
                }

                sb.AppendLine("        }");
            }

            sb.AppendLine("    }");
            sb.AppendLine();
        }

        // ClearAllEntities
        sb.AppendLine("    /// <summary>Clears all entities and components</summary>");
        sb.AppendLine("    public void ClearAllEntities()");
        sb.AppendLine("    {");
        sb.AppendLine("        _nextEntityId = 1;");
        sb.AppendLine("        _freeEntityIds.Clear();");
        foreach (var component in components)
        {
            if (component.Flags.HasFlag(ComponentFlags.Dense))
            {
                sb.AppendLine($"        Array.Clear(_data_{component.Name}, 0, _data_{component.Name}.Length);");
                sb.AppendLine($"        _set_{component.Name}.SetAll(false);");

                if (component.Flags.HasFlag(ComponentFlags.DirtyTracked))
                {
                    sb.AppendLine($"        _dirty_{component.Name}.SetAll(false);");
                }
            }
            else // Sparse
            {
                sb.AppendLine($"        _data_{component.Name}.Clear();");
                sb.AppendLine($"        _set_{component.Name}.Clear();");

                if (component.Flags.HasFlag(ComponentFlags.DirtyTracked))
                {
                    sb.AppendLine($"        _dirty_{component.Name}.Clear();");
                }
            }
        }

        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine();
    }
