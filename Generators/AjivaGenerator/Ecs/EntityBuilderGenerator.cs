using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AjivaGenerator.Ecs;

/// <summary>
/// Generates the fluent EntityBuilder class for clean entity creation
/// </summary>
internal static class EntityBuilderGenerator
{
    public static void GenerateEntityBuilder(SourceProductionContext context, ImmutableArray<ComponentInfo> components)
    {
        var sourceCode = BuildEntityBuilderClass(components);
        context.AddSource("EntityBuilder.g.cs", SourceText.From(sourceCode, Encoding.UTF8));
    }

    private static string BuildEntityBuilderClass(ImmutableArray<ComponentInfo> components)
    {
        var sb = new StringBuilder();
        
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Numerics;");
        sb.AppendLine("using Common.EcsV2;");
        sb.AppendLine("using Common.SpacialPartitioning;");
        sb.AppendLine();
        sb.AppendLine("namespace Common.EcsV2;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Fluent entity builder for clean entity creation syntax");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public ref struct EntityBuilder");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly EcsWorld _world;");
        sb.AppendLine("    private readonly EntityId _entity;");
        sb.AppendLine();
        sb.AppendLine("    internal EntityBuilder(EcsWorld world, EntityId entity)");
        sb.AppendLine("    {");
        sb.AppendLine("        _world = world;");
        sb.AppendLine("        _entity = entity;");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Generate Add methods for each component
        foreach (var component in components)
        {
            GenerateComponentBuilderMethod(sb, component);
        }

        // Generate helper methods
        GenerateHelperMethods(sb, components);

        // Generate implicit conversion
        sb.AppendLine("    /// <summary>Implicit conversion to EntityId for seamless usage</summary>");
        sb.AppendLine("    public static implicit operator EntityId(EntityBuilder builder) => builder._entity;");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Explicit build method if preferred over implicit conversion</summary>");
        sb.AppendLine("    public EntityId Build() => _entity;");
        sb.AppendLine("}");
        sb.AppendLine();

        // Generate extension method for EcsWorld
        GenerateEcsWorldExtension(sb);

        return sb.ToString();
    }

    private static void GenerateComponentBuilderMethod(StringBuilder sb, ComponentInfo component)
    {
        var name = component.Name;
        var fields = component.Fields;

        sb.AppendLine($"    /// <summary>Adds a {name} component with optional field values</summary>");

        if (fields.Any())
        {
            // Generate method with optional parameters for each field
            sb.Append($"    public EntityBuilder Add{name}(");
            
            var parameters = fields.Select(field => $"{field.TypeName}? {ToCamelCase(field.Name)} = null").ToArray();
            sb.Append(string.Join(", ", parameters));
            sb.AppendLine(")");
            sb.AppendLine("    {");
            sb.AppendLine($"        var component = new {name}");
            sb.AppendLine("        {");
            
            foreach (var field in fields)
            {
                var paramName = ToCamelCase(field.Name);
                sb.AppendLine($"            {field.Name} = {paramName} ?? GetDefaultValue<{field.TypeName}>(),");
            }
            
            sb.AppendLine("        };");
            sb.AppendLine($"        _world.Add{name}(_entity, component);");
            sb.AppendLine("        return this;");
            sb.AppendLine("    }");
            sb.AppendLine();

            // Also generate method that takes the full component
            sb.AppendLine($"    /// <summary>Adds a {name} component with a complete component instance</summary>");
            sb.AppendLine($"    public EntityBuilder Add{name}(in {name} component)");
            sb.AppendLine("    {");
            sb.AppendLine($"        _world.Add{name}(_entity, component);");
            sb.AppendLine("        return this;");
            sb.AppendLine("    }");
        }
        else
        {
            // For components with no fields, just add the default
            sb.AppendLine($"    public EntityBuilder Add{name}()");
            sb.AppendLine("    {");
            sb.AppendLine($"        _world.Add{name}(_entity, default);");
            sb.AppendLine("        return this;");
            sb.AppendLine("    }");
        }

        sb.AppendLine();
    }

    private static void GenerateHelperMethods(StringBuilder sb, ImmutableArray<ComponentInfo> components)
    {
        // Check if we have common transform components
        var hasPosition = components.Any(c => c.Name == "Position");
        var hasRotation = components.Any(c => c.Name == "Rotation");
        var hasScale = components.Any(c => c.Name == "Scale");

        if (hasPosition && hasRotation && hasScale)
        {
            sb.AppendLine("    /// <summary>Adds a complete transform (Position + Rotation + Scale) with default values</summary>");
            sb.AppendLine("    public EntityBuilder AddTransform(Vector3? position = null, Quaternion? rotation = null, Vector3? scale = null, int level = 0)");
            sb.AppendLine("    {");
            sb.AppendLine("        return AddPosition(position ?? Vector3.Zero, level)");
            sb.AppendLine("               .AddRotation(rotation ?? Quaternion.Identity)");
            sb.AppendLine("               .AddScale(scale ?? Vector3.One);");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        // Add default value helper
        sb.AppendLine("    /// <summary>Gets the default value for a type</summary>");
        sb.AppendLine("    private static T GetDefaultValue<T>() => default(T)!;");
        sb.AppendLine();
    }

    private static void GenerateEcsWorldExtension(StringBuilder sb)
    {
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Extension methods for EcsWorld to enable fluent entity creation");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class EcsWorldExtensions");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>Creates a new entity and returns a fluent builder</summary>");
        sb.AppendLine("    public static EntityBuilder CreateEntity(this EcsWorld world)");
        sb.AppendLine("    {");
        sb.AppendLine("        var entity = world.CreateEntity();");
        sb.AppendLine("        return new EntityBuilder(world, entity);");
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    private static string ToCamelCase(string input)
    {
        if (string.IsNullOrEmpty(input) || char.IsLower(input[0]))
            return input;
        
        return char.ToLowerInvariant(input[0]) + input.Substring(1);
    }
}
