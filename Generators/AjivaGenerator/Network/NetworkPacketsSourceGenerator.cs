    private static ushort FindCoprimeIncrement(ushort count) => 1; // Simplified
    private static int Gcd(ushort a, ushort b) => 1; // Simplified
}

/// <summary>
/// A helper class to build strings with consistent indentation.
/// </summary>
internal class IndentedStringBuilder
{
    private readonly StringBuilder _builder = new();
    private int _indentLevel;
    private const string IndentString = "    "; // 4 spaces for indentation

    public void Indent() => _indentLevel++;

    public void Unindent()
    {
        if (_indentLevel > 0)
        {
            _indentLevel--;
        }
    }

    public void AppendLine(string line = "")
    {
        if (!string.IsNullOrEmpty(line))
        {
            for (int i = 0; i < _indentLevel; i++)
            {
                _builder.Append(IndentString);
            }
        }

        _builder.AppendLine(line);
    }

    public void EnterScope(char open = '{')
    {
        AppendLine(open.ToString());
        Indent();
    }

    public void ExitScope(char close = '}', bool addSemicolon = false)
    {
        Unindent();
        var line = close.ToString();
        if (addSemicolon)
        {
            line += ";";
        }

        AppendLine(line);
    }

    public override string ToString() => _builder.ToString();
}
