    private const string AttributeName = "NetworkPacketAttribute";
    private const string AutoGenHeader = "// <auto-generated/>\n#nullable enable\n#nullable disable warnings\n";

    private const string AttributeSourceCode =
        $$"""
          {{AutoGenHeader}}
          using System.Buffers;
          
          namespace {{Namespace}};
          [global::System.AttributeUsage(global::System.AttributeTargets.Struct)] // Changed to Struct only
          public class {{AttributeName}} : global::System.Attribute
          {
              public ushort PacketId { get; }

              public {{AttributeName}}(ushort packetId)
              {
                  PacketId = packetId;
              }
          }

          public interface IPacket
          {   /*
              public void Send(global::Riptide.Connection connection, global::Riptide.MessageSendMode sendMode);
              public void SendToAll(global::Riptide.Server server, global::Riptide.MessageSendMode sendMode);
              public bool TryToMessage(global::System.Span<byte> buffer);    */
          }

          public readonly ref struct SerializedMessage(global::MemoryPack.Internal.ReusableLinkedArrayBufferWriter _writer) : IDisposable
          {
              public void Dispose()
              {
                  global::MemoryPack.Internal.ReusableLinkedArrayBufferWriterPool.Return(Writer);
              }
              
              public global::MemoryPack.Internal.ReusableLinkedArrayBufferWriter.Enumerator GetEnumerator()
              {
                  return new global::MemoryPack.Internal.ReusableLinkedArrayBufferWriter.Enumerator(_writer);
              }
              
              public ulong Length => (ulong)_writer.TotalWritten;
              public global::MemoryPack.Internal.ReusableLinkedArrayBufferWriter Writer => _writer;
          }

          public interface IQConnection
          {
              void Send(SerializedMessage message);
          }

          public interface IQServer
          {
              void SendToAll(SerializedMessage message);
          }
          
          /// <summary>
          /// Provides high-performance, allocation-free helper methods for variable-length
          /// bitpacking of 64-bit integers using Varint and ZigZag encoding.
          /// These methods are designed as extension methods for Span, ReadOnlySpan, and IBufferWriter.
          /// </summary>
          public static class BitPackingHelper
          {
              public const i32 MaxVarLength = 10;
          
              /// <summary>
              /// Attempts to read a Varint-encoded 64-bit unsigned integer from the start of the span.
              /// This method does not throw an exception on failure.
              /// </summary>
              /// <param name="data">The span of bytes to read from.</param>
              /// <param name="value">When this method returns, contains the decoded ulong value if successful; otherwise, 0.</param>
              /// <param name="bytesRead">When this method returns, contains the number of bytes read if successful; otherwise, 0.</param>
              /// <returns>true if the value was successfully decoded; otherwise, false.</returns>
              public static bool TryReadVarU64(this ReadOnlySpan<u8> data, out u64 value, out i32 bytesRead)
              {
                  value = 0;
                  var shift = 0;
          
                  for (var i = 0; i < data.Length; i++)
                  {
                      var b = data[i];
          
                      // A 64-bit varint can be at most 10 bytes long.
                      if (i >= MaxVarLength)
                      {
                          bytesRead = 0;
                          value = 0;
                          return false; // Malformed: Varint is too long
                      }
          
                      value |= (u64)(b & 0x7F) << shift;
          
                      if ((b & 0x80) == 0)
                      {
                          bytesRead = i + 1;
                          return true; // Successfully decoded
                      }
          
                      shift += 7;
                  }
          
                  // If we exit the loop, it means the data was incomplete.
                  bytesRead = 0;
                  value = 0;
                  return false;
              }
          
              /// <summary>
              /// Attempts to decode a Varint-encoded 64-bit unsigned integer from the span,
              /// advancing the span past the consumed bytes if successful.
              /// </summary>
              /// <param name="data">The span of bytes to read from. It will be sliced on success.</param>
              /// <param name="value">When this method returns, contains the decoded ulong value if successful.</param>
              /// <returns>true if the value was successfully consumed; otherwise, false.</returns>
              public static bool TryConsumeVarU64(ref this ReadOnlySpan<u8> data, out u64 value)
              {
                  if (data.TryReadVarU64(out value, out i32 bytesRead))
                  {
                      data = data.Slice(bytesRead);
                      return true;
                  }
          
                  return false;
              }
          
          
              /// <summary>
              /// Reads a Varint-encoded 64-bit unsigned integer from the start of the span. Throws on failure.
              /// </summary>
              /// <returns>A tuple containing the decoded ulong value and the number of bytes read.</returns>
              /// <exception cref="InvalidDataException">Thrown if the data is malformed or incomplete.</exception>
              public static u64 ReadVarU64(this ReadOnlySpan<u8> data, out i32 bytesRead)
              {
                  if (data.TryReadVarU64(out u64 value, out bytesRead))
                  {
                      return value;
                  }
          
                  throw new InvalidDataException("Malformed or incomplete Varint data.");
              }
          
              /// <summary>
              /// Decodes a Varint-encoded 64-bit unsigned integer from the span, advancing it. Throws on failure.
              /// </summary>
              /// <returns>The decoded ulong value.</returns>
              /// <exception cref="InvalidDataException">Thrown if the data is malformed or incomplete.</exception>
              public static u64 ConsumeVarU64(ref this ReadOnlySpan<u8> data)
              {
                  if (data.TryReadVarU64(out u64 value, out i32 bytesRead))
                  {
                      data = data.Slice(bytesRead);
                      return value;
                  }
          
                  throw new InvalidDataException("Malformed or incomplete Varint data.");
              }
          
          
              /// <summary>
              /// Encodes a 64-bit unsigned integer using Varint encoding into the destination span.
              /// </summary>
              public static i32 PackVarU64(this Span<u8> destination, u64 value)
              {
                  i32 bytesWritten = 0;
                  do
                  {
                      if (bytesWritten >= destination.Length)
                      {
                          throw new ArgumentException("Destination span is too small.", nameof(destination));
                      }
          
                      u8 b = (u8)(value & 0x7F);
                      value >>= 7;
                      if (value > 0) b |= 0x80;
                      destination[bytesWritten++] = b;
                  } while (value > 0);
          
                  return bytesWritten;
              }
          
              /// <summary>
              /// Encodes a 64-bit unsigned integer using Varint and writes it to an IBufferWriter.
              /// </summary>
              public static void PackVarU64(this IBufferWriter<u8> writer, u64 value)
              {
                  Span<u8> buffer = writer.GetSpan(MaxVarLength);
                  i32 bytesWritten = buffer.PackVarU64(value);
                  writer.Advance(bytesWritten);
              }
          
          
              /// <summary>
              /// Attempts to read a ZigZag/Varint-encoded 64-bit signed integer from the start of the span.
              /// </summary>
              /// <returns>true if the value was successfully decoded; otherwise, false.</returns>
              public static bool TryReadVarI64(this ReadOnlySpan<u8> data, out long value, out i32 bytesRead)
              {
                  if (data.TryReadVarU64(out u64 zigzagValue, out bytesRead))
                  {
                      // ZigZag decode
                      value = (long)(zigzagValue >> 1) ^ -(long)(zigzagValue & 1);
                      return true;
                  }
          
                  value = 0;
                  return false;
              }
          
              /// <summary>
              /// Attempts to decode a ZigZag/Varint-encoded 64-bit signed integer, advancing the span on success.
              /// </summary>
              public static bool TryConsumeVarI64(ref this ReadOnlySpan<u8> data, out long value)
              {
                  if (data.TryReadVarI64(out value, out i32 bytesRead))
                  {
                      data = data.Slice(bytesRead);
                      return true;
                  }
          
                  return false;
              }
          
          
              /// <summary>
              /// Reads a ZigZag/Varint-encoded 64-bit signed integer from the start of the span. Throws on failure.
              /// </summary>
              public static long ReadVarI64(this ReadOnlySpan<u8> data, out i32 bytesRead)
              {
                  if (data.TryReadVarI64(out long value, out bytesRead))
                  {
                      return value;
                  }
          
                  throw new InvalidDataException("Malformed or incomplete ZigZag/Varint data.");
              }
          
              /// <summary>
              /// Decodes a ZigZag/Varint-encoded 64-bit signed integer, advancing the span. Throws on failure.
              /// </summary>
              public static long ConsumeVarI64(ref this ReadOnlySpan<u8> data)
              {
                  if (data.TryReadVarI64(out long value, out i32 bytesRead))
                  {
                      data = data.Slice(bytesRead);
                      return value;
                  }
          
                  throw new InvalidDataException("Malformed or incomplete ZigZag/Varint data.");
              }
          
          
              /// <summary>
              /// Encodes a 64-bit signed integer using ZigZag and Varint encoding into the destination span.
              /// </summary>
              public static i32 PackVarI64(this Span<u8> destination, long value)
              {
                  u64 zigzagValue = (u64)((value << 1) ^ (value >> 63));
                  return destination.PackVarU64(zigzagValue);
              }
          
              /// <summary>
              /// Encodes a 64-bit signed integer using ZigZag/Varint and writes it to an IBufferWriter.
              /// </summary>
              public static void PackVarI64(this IBufferWriter<u8> writer, long value)
              {
                  u64 zigzagValue = (u64)((value << 1) ^ (value >> 63));
                  writer.PackVarU64(zigzagValue);
              }
          }
          
          """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx => ctx.AddSource(
            "NetworkPacketAttribute.g.cs",
            SourceText.From(AttributeSourceCode, Encoding.UTF8)));

        var provider = context.SyntaxProvider
            .CreateSyntaxProvider(
                (s, _) => s is TypeDeclarationSyntax, // Can be refined to `is StructDeclarationSyntax`
                (ctx, _) => GetPacketDeclarationForSourceGen(ctx))
            .Where(t => t.reportAttributeFound)
            .Select((t, _) => (t.Item1, t.Item2));

        context.RegisterSourceOutput(context.CompilationProvider.Combine(provider.Collect()),
            (ctx, t) => GenerateCode(ctx, t.Left, t.Right));
    }

    private static (TypeDeclarationSyntax, ushort, bool reportAttributeFound) GetPacketDeclarationForSourceGen(
        GeneratorSyntaxContext context)
    {
        var declarationSyntax = (TypeDeclarationSyntax)context.Node;

        foreach (AttributeListSyntax attributeListSyntax in declarationSyntax.AttributeLists)
        foreach (AttributeSyntax attributeSyntax in attributeListSyntax.Attributes)
        {
            if (context.SemanticModel.GetSymbolInfo(attributeSyntax).Symbol is not IMethodSymbol attributeSymbol)
                continue;

            string attributeName = attributeSymbol.ContainingType.ToDisplayString();
            if (attributeName == $"{Namespace}.{AttributeName}")
            {
                if (attributeSyntax.ArgumentList is { Arguments: { Count: > 0 } arguments } &&
                    arguments[0].Expression is LiteralExpressionSyntax { Token.Value: int packetId })
                {
                    return (declarationSyntax, (ushort)packetId, true);
                }
            }
        }

        return (declarationSyntax, 0, false);
    }

    private void GenerateCode(SourceProductionContext context, Compilation compilation,
        ImmutableArray<(TypeDeclarationSyntax, ushort)> declarations)
    {
        if (declarations.IsDefaultOrEmpty)
        {
            return;
        }

        var packetTypes = new List<(string Name, ushort Id)>();
        var packetDetails =
            new List<(string Namespace, string ClassName,
                List<(ITypeSymbol Type, string FieldName, string OriginalName)> Fields)>();
        var seenPacketIds = new HashSet<ushort>();

        foreach (var (declarationSyntax, packageTypeId) in declarations)
        {
            var semanticModel = compilation.GetSemanticModel(declarationSyntax.SyntaxTree);
            if (semanticModel.GetDeclaredSymbol(declarationSyntax) is not { } symbol)
                continue;

            if (symbol.TypeKind != TypeKind.Struct)
            {
                context.ReportDiagnostic(Diagnostic.Create(NetworkGeneratorRules.MustBeStructRule,
                    declarationSyntax.GetLocation(), symbol.ToDisplayString()));
                continue;
            }

            var namespaceName = symbol.ContainingNamespace.ToDisplayString();
            var className = declarationSyntax.Identifier.Text;

            var fields = new List<(ITypeSymbol Type, string FieldName, string OriginalName)>();
            if (declarationSyntax is StructDeclarationSyntax { ParameterList: { } parameterList })
            {
                foreach (var parameter in parameterList.Parameters)
                {
                    if (semanticModel.GetDeclaredSymbol(parameter) is { } paramSymbol)
                    {
                        fields.Add((paramSymbol.Type, "_" + parameter.Identifier.Text, parameter.Identifier.Text));
                    }
                }
            }

            var source = GeneratePacketSource(context, symbol, namespaceName, className, fields);
            context.AddSource($"{className}.g.cs", SourceText.From(source, Encoding.UTF8));

            ushort enumId = packageTypeId;
            while (seenPacketIds.Contains(enumId))
            {
                // Simple collision avoidance, can be made more robust
                enumId++;
            }

            seenPacketIds.Add(enumId);

            packetTypes.Add((className, enumId));
            packetDetails.Add((namespaceName, className, fields));
        }

        if (packetDetails.Any())
        {
            context.AddSource("PacketType.g.cs",
                SourceText.From(GeneratePacketTypeEnumSource(packetTypes), Encoding.UTF8));
            context.AddSource("UniversalMessageHandlers.g.cs",
                SourceText.From(GenerateHandlersSource(packetDetails), Encoding.UTF8));
            context.AddSource("MessageHandlerExtensions.g.cs",
                SourceText.From(GenerateMessageHandlerExtensionsSource(packetDetails), Encoding.UTF8));
        }
    }

    private string GeneratePacketSource(SourceProductionContext context, INamedTypeSymbol symbol, string namespaceName,
        string className, List<(ITypeSymbol Type, string FieldName, string OriginalName)> fields)
    {
        var sb = new IndentedStringBuilder();

        sb.AppendLine(AutoGenHeader);

        // Add required usings
        sb.AppendLine("using NetworkPackets;");
        sb.AppendLine("using System.Buffers;");
        sb.AppendLine("using System.Diagnostics;");
        sb.AppendLine();

        sb.AppendLine($"namespace {namespaceName};");
        sb.AppendLine();

        var accessibility = symbol.DeclaredAccessibility.ToString().ToLowerInvariant();
        sb.AppendLine($"{accessibility} partial {(symbol.IsRecord ? "record " : " ")}struct {className} : IPacket");
        sb.EnterScope(); // Struct scope

        // Generate Fields and Properties
        foreach (var (type, fieldName, originalName) in fields)
        {
            var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var propertyName = NetworkPacketGenerationHelper.ToPascalCase(originalName);

            sb.AppendLine($"private {typeName} {fieldName} = {originalName};");
            sb.AppendLine($"public {typeName} {propertyName}");
            sb.EnterScope(); // Property scope
            sb.AppendLine($"get => {fieldName};");
            sb.AppendLine($"set => {fieldName} = value;");
            sb.ExitScope(); // Property scope
            sb.AppendLine();
        }

        // ToMessage Method
        sb.AppendLine("public SerializedMessage ToMessage()");
        sb.EnterScope();
        sb.AppendLine($"var writer = global::MemoryPack.Internal.ReusableLinkedArrayBufferWriterPool.Rent();");
        sb.AppendLine("Serialize(writer);");
        sb.AppendLine("return new SerializedMessage(writer);");
        sb.ExitScope();
        sb.AppendLine();


        // Serialize Method
        sb.AppendLine("public void Serialize(global::MemoryPack.Internal.ReusableLinkedArrayBufferWriter writer)");
        sb.EnterScope();
        sb.AppendLine("Span<byte> typeSpan = stackalloc byte[BitPackingHelper.MaxVarLength];");
        sb.AppendLine($"var prefixBytes = BitPackingHelper.PackVarU64(typeSpan, (ulong)PacketType.{className});");
        sb.AppendLine("writer.Write(typeSpan[..prefixBytes]);");
        sb.AppendLine("global::MemoryPack.MemoryPackSerializer.Serialize(writer, this);");

        sb.ExitScope();
        sb.AppendLine();

        // Send Methods
        sb.AppendLine("public void Send(IQConnection connection)");
        sb.EnterScope();
        sb.AppendLine("using var msg = ToMessage();");
        sb.AppendLine("connection.Send(msg);");
        sb.ExitScope();

        sb.AppendLine("public void SendToAll(IQServer server)");
        sb.EnterScope();
        sb.AppendLine("using var msg = ToMessage();");
        sb.AppendLine("server.SendToAll(msg);");
        sb.ExitScope();
        sb.AppendLine();

        // Deserialize static factory
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Deserializes the packet from the given data span.");
        sb.AppendLine("/// <remarks>Assumes the PacketType prefix has already been read.</remarks>");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"public static {className} Deserialize(global::System.ReadOnlySpan<byte> data)");
        sb.EnterScope();
        sb.AppendLine($"var packet = new {className}();");
        sb.AppendLine("var read = global::MemoryPack.MemoryPackSerializer.Deserialize(data, ref packet);");
        sb.AppendLine(
            $$"""Debug.Assert(read == data.Length, $"Did not read entire buffer when deserializing {{nameof(className)}}. Read {read} of {data.Length} bytes.");""");
        sb.AppendLine("return packet;");
        sb.ExitScope();
        sb.AppendLine();

        sb.ExitScope(); // Struct scope

        return sb.ToString();
    }

    private string GeneratePacketTypeEnumSource(List<(string Name, ushort Id)> packetTypes)
    {
        var sb = new IndentedStringBuilder();
        sb.AppendLine(AutoGenHeader);
        sb.AppendLine($"namespace {Namespace};");
        sb.AppendLine();
        sb.AppendLine("public enum PacketType : ushort");
        sb.EnterScope();
        foreach (var (name, id) in packetTypes)
        {
            sb.AppendLine($"{name} = {id},");
        }

        sb.ExitScope();
        return sb.ToString();
    }

    private string GenerateHandlersSource(
        List<(string Namespace, string ClassName,
            List<(ITypeSymbol Type, string FieldName, string OriginalName)> Fields)> packetDetails)
    {
        var sb = new IndentedStringBuilder();
        sb.AppendLine(AutoGenHeader);
        sb.AppendLine($"namespace {Namespace};");
        sb.AppendLine();

        // Async Handler Interface
        sb.AppendLine("public interface IUniversalAsyncMessageHandler<TUserData>");
        sb.EnterScope();
        foreach (var (ns, className, _) in packetDetails)
        {
            sb.AppendLine(
                $"public global::System.Threading.Tasks.Task HandleAsync({ns}.{className} message, TUserData userData) => MessageNotHandledAsync(\"{ns}.{className}\", userData);");
        }

        sb.AppendLine(
            "public global::System.Threading.Tasks.Task MessageNotHandledAsync(string messageType, TUserData userData) => global::System.Threading.Tasks.Task.CompletedTask;");
        sb.ExitScope();
        sb.AppendLine();

        // Sync Handler Interface
        sb.AppendLine("public interface IUniversalMessageHandler<TUserData>");
        sb.EnterScope();
        foreach (var (ns, className, _) in packetDetails)
        {
            sb.AppendLine(
                $"public void Handle({ns}.{className} message, TUserData userData) => MessageNotHandled(\"{ns}.{className}\", userData);");
        }

        sb.AppendLine("public void MessageNotHandled(string messageType, TUserData userData) { }");
        sb.ExitScope();

        return sb.ToString();
    }

    private string GenerateMessageHandlerExtensionsSource(
        List<(string Namespace, string ClassName, List<(ITypeSymbol Type, string FieldName, string OriginalName)> Fields
            )> packetDetails)
    {
        var sb = new IndentedStringBuilder();
        sb.AppendLine(AutoGenHeader);
        sb.AppendLine($"namespace {Namespace};");
        sb.AppendLine();
        sb.AppendLine("public static class MessageHandlerExtensions");
        sb.EnterScope();


        // Async HandleMessage Method
        sb.AppendLine(
            "public static global::System.Threading.Tasks.Task AutoHandleAsync<TUserData>(this IUniversalAsyncMessageHandler<TUserData> handler, global::System.ReadOnlySpan<byte> span, TUserData userData)");
        sb.EnterScope();
        sb.AppendLine("var type = (PacketType)span.ConsumeVarU64();");
        sb.AppendLine("return type switch");
        sb.EnterScope('{'); // Switch expression scope
        foreach (var (ns, className, _) in packetDetails)
        {
            sb.AppendLine(
                $"PacketType.{className} => handler.HandleAsync({ns}.{className}.Deserialize(span), userData),");
        }

        sb.AppendLine("_ => throw new global::System.ArgumentOutOfRangeException(nameof(type), type, null)");
        sb.ExitScope(addSemicolon: true); // End switch expression with semicolon
        sb.ExitScope();
        sb.AppendLine();

        // Sync HandleMessage Method
        sb.AppendLine(
            "public static void AutoHandle<TUserData>(this IUniversalMessageHandler<TUserData> handler, global::System.ReadOnlySpan<byte> span, TUserData userData)");
        sb.EnterScope();
        sb.AppendLine("var type = (PacketType)span.ConsumeVarU64();");
        sb.AppendLine("switch (type)");
        sb.EnterScope();
        foreach (var (ns, className, _) in packetDetails)
        {
            sb.AppendLine($"case PacketType.{className}:");
            sb.Indent();
            sb.AppendLine($"handler.Handle({ns}.{className}.Deserialize(span), userData);");
            sb.AppendLine("break;");
            sb.Unindent();
        }

        sb.ExitScope();
        sb.ExitScope();

        sb.ExitScope();
        return sb.ToString();
    }

    private static string GetGetMethodName(ITypeSymbol typeSymbol, SourceProductionContext context)
    {
        string typeName = typeSymbol.ToDisplayString();

        switch (typeName)
        {
            case "string": return "GetString";
            case "bool": return "GetBool";
            case "byte": return "GetByte";
            case "sbyte": return "GetSByte";
            case "short": return "GetShort";
            case "ushort": return "GetUShort";
            case "int": return "GetInt";
            case "uint": return "GetUInt";
            case "long": return "GetLong";
            case "ulong": return "GetULong";
            case "float": return "GetFloat";
            case "double": return "GetDouble";
            case "System.Numerics.Vector2": return "GetVector2";
            case "System.Numerics.Vector3": return "GetVector3";
            case "System.Numerics.Quaternion": return "GetQuaternion";
        }

        // Handle arrays
        if (typeSymbol is IArrayTypeSymbol arrayType)
        {
            var elementMethod = GetGetMethodName(arrayType.ElementType, context).Replace("Get", "");
            return $"Get{elementMethod}s"; // e.g., GetBools, GetInts
        }

        // Handle Enums by getting their underlying type
        if (typeSymbol.TypeKind == TypeKind.Enum && typeSymbol is INamedTypeSymbol namedType)
        {
            return GetGetMethodName(namedType.EnumUnderlyingType!, context);
        }

        // Fallback for custom IMessageSerializable types
        if (typeSymbol.AllInterfaces.Any(i => i.ToDisplayString() == "Riptide.IMessageSerializable"))
        {
            return $"GetSerializable<{typeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}>";
        }

        // Report an error if no method is found
        context.ReportDiagnostic(Diagnostic.Create(NetworkGeneratorRules.UnsupportedFieldTypeRule,
            typeSymbol.Locations.FirstOrDefault(), typeName));
        return $"Get<{typeName}>"; // Return a generic as a fallback to avoid breaking compilation
    }

