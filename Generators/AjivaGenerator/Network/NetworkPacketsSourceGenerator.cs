using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Diagnostics;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace AjivaGenerator.Network;

[Generator]
public class NetworkPacketsSourceGenerator : IIncrementalGenerator
{
    private const string Namespace = "NetworkPackets";
    private const string AttributeName = "NetworkPacketAttribute";
    private const string GroupAttributeName = "NetworkPacketGroupAttribute";
    private const string AutoGenHeader = "// <auto-generated/>\n#nullable enable\n#nullable disable warnings\n";

    private const string AttributeSourceCode =
        $$"""
          {{AutoGenHeader}}
          using System.Buffers;
          using MemoryPack;
          using MemoryPack.Internal;

          namespace {{Namespace}};

          /// <summary>
          /// Marks a class as a network packet group. All nested structs with [NetworkPacket] become packets.
          /// Can be applied multiple times with different handler types for composition.
          /// </summary>
          [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = true)]
          public class NetworkPacketGroupAttribute : global::System.Attribute
          {
              public string GroupName { get; }

              /// <summary>
              /// Creates a new NetworkPacketGroup attribute with the specified group name.
              /// </summary>
              /// <param name="groupName">The name of the packet group. Can be any string, but should be unique per handler type. Accepts "*" as wildcard to include in all groups.</param>
              public NetworkPacketGroupAttribute(string groupName)
              {
                  GroupName = groupName;
              }
          }

          /// <summary>
          /// Marks a struct as a network packet. When used inside a [NetworkPacketGroup] class, only packet ID is needed.
          /// Packet IDs only need to be unique within the same handler type.
          /// </summary>
          [global::System.AttributeUsage(global::System.AttributeTargets.Struct)]
          public class {{AttributeName}} : global::System.Attribute
          {
              public ushort PacketId { get; }

              public {{AttributeName}}(ushort packetId)
              {
                  PacketId = packetId;
              }
          }

          public interface IPacket
          {
          }

          public ref struct SerializedMessage() : IDisposable
          {
              public ReusableLinkedArrayBufferWriter Writer = ReusableLinkedArrayBufferWriterPool.Rent();
              public MemoryPackWriterOptionalState State = MemoryPackWriterOptionalStatePool.Rent(MemoryPackSerializerOptions.Default);

              public void Dispose()
              {
                  ReusableLinkedArrayBufferWriterPool.Return(Writer);
                  ((IDisposable)State).Dispose();
              }
              
              public ReusableLinkedArrayBufferWriter.Enumerator GetEnumerator()
              {
                  return new ReusableLinkedArrayBufferWriter.Enumerator(Writer);
              }
              
              public ulong Length => (ulong)Writer.TotalWritten;
          }
          """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx => ctx.AddSource(
            "NetworkPacketAttribute.g.cs",
            SourceText.From(AttributeSourceCode, Encoding.UTF8)));

        return;
        // Find all classes with [NetworkPacketGroup] attribute
        var provider = context.SyntaxProvider
            .CreateSyntaxProvider(
                (s, _) => s is ClassDeclarationSyntax,
                (ctx, _) => GetPacketGroupForSourceGen(ctx))
            .Where(t => t is not null)
            .Select((t, _) => t!);

        context.RegisterSourceOutput(context.CompilationProvider.Combine(provider.Collect()),
            (ctx, t) => GenerateCode(ctx, t.Left, t.Right));
    }

    private static ClassDeclarationSyntax? GetPacketGroupForSourceGen(GeneratorSyntaxContext context)
    {
        var classSyntax = (ClassDeclarationSyntax)context.Node;
        foreach (var attributeSyntax in classSyntax.AttributeLists.SelectMany(attributeListSyntax =>
                     attributeListSyntax.Attributes))
        {
            if (context.SemanticModel.GetSymbolInfo(attributeSyntax).Symbol is not IMethodSymbol attributeSymbol)
                continue;

            if (attributeSymbol.ContainingType.ToDisplayString() == $"{Namespace}.{GroupAttributeName}")
            {
                return classSyntax;
            }
        }

        return null;
    }

    private void GenerateCode(SourceProductionContext context, Compilation compilation,
        ImmutableArray<ClassDeclarationSyntax> groupDeclarations)
    {
        List<string> allGroupNames = [];
        List<(string className, ushort Value, string fullyQualifiedName, List<string> groupNames, TypeDeclarationSyntax
            member, INamedTypeSymbol symbol)> packetDetails = [];
        foreach (var groupDeclaration in groupDeclarations)
        {
            List<string> groupNames = [];
            foreach (var attributeList in groupDeclaration.AttributeLists)
            {
                foreach (var attribute in attributeList.Attributes)
                {
                    if (GroupAttributeName.StartsWith(attribute.Name.ToString()))
                    {
                        var groupName = attribute.ArgumentList?.Arguments.FirstOrDefault()?.ToString().Trim('"');
                        if (string.IsNullOrEmpty(groupName))
                        {
                            context.ReportDiagnostic(Diagnostic.Create(NetworkGeneratorRules.InvalidAttributeRule,
                                attribute.GetLocation(), groupDeclaration.Identifier.Text,
                                "Group name cannot be empty"));
                        }
                        else
                        {
                            groupNames.Add(groupName!);
                        }
                    }
                }
            }

            if (groupNames.Count == 0)
            {
                context.ReportDiagnostic(Diagnostic.Create(NetworkGeneratorRules.InvalidAttributeRule,
                    groupDeclaration.Identifier.GetLocation(), groupDeclaration.Identifier.Text,
                    "Class marked with [NetworkPacketGroup] must have a valid group name"));
                continue;
            }

            allGroupNames.AddRange(groupNames);

            foreach (var member in groupDeclaration.Members.OfType<TypeDeclarationSyntax>())
            {
                if (member is not RecordDeclarationSyntax)
                {
                    context.ReportDiagnostic(Diagnostic.Create(NetworkGeneratorRules.MustBeRecordStructRule,
                        member.GetLocation(), member.ToString()));
                    continue;
                }

                var semanticModel = compilation.GetSemanticModel(member.SyntaxTree);
                if (semanticModel.GetDeclaredSymbol(member) is not INamedTypeSymbol memberSymbol)
                    continue;

                bool hasPacketAttribute, hasMemoryPackable;
                hasPacketAttribute = hasMemoryPackable = false;
                ushort? packetId = null;
                foreach (var attrList in member.AttributeLists)
                {
                    foreach (var attr in attrList.Attributes)
                    {
                        if (semanticModel.GetSymbolInfo(attr).Symbol is IMethodSymbol attrSymbol)
                        {
                            var attrName = attrSymbol.ContainingType.ToDisplayString();
                            if (attrName == $"{Namespace}.{AttributeName}")
                            {
                                hasPacketAttribute = true;
                                if (attr.ArgumentList?.Arguments is
                                    [
                                        {
                                            Expression: LiteralExpressionSyntax
                                            {
                                                Token.Value: int id
                                            }
                                        }
                                    ])
                                {
                                    packetId = (ushort)id;
                                }
                            }
                            else if (attrName == "MemoryPack.MemoryPackableAttribute")
                            {
                                hasMemoryPackable = true;
                            }
                        }
                    }
                }

                if (!hasPacketAttribute)
                {
                    context.ReportDiagnostic(Diagnostic.Create(NetworkGeneratorRules.InvalidAttributeRule,
                        member.GetLocation(), memberSymbol.Name,
                        "Nested struct in NetworkPacketGroup must have [NetworkPacket(id)] attribute"));
                    continue;
                }

                if (!packetId.HasValue)
                {
                    context.ReportDiagnostic(Diagnostic.Create(NetworkGeneratorRules.InvalidAttributeRule,
                        member.GetLocation(), memberSymbol.Name,
                        "NetworkPacket attribute must have a valid packet ID"));
                    continue;
                }

                if (!hasMemoryPackable)
                {
                    context.ReportDiagnostic(Diagnostic.Create(NetworkGeneratorRules.InvalidAttributeRule,
                        member.GetLocation(), memberSymbol.Name,
                        "Packet struct must have [MemoryPackable] attribute"));
                    continue;
                }

                var fullyQualifiedName = memberSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var className = memberSymbol.Name;

                packetDetails.Add((className, packetId.Value, fullyQualifiedName, groupNames, member, memberSymbol));
            }
        }

        if (packetDetails.Any())
        {
            if (!CheckPackets(context, packetDetails))
                return;

            foreach (var (className, _, fullyQualifiedName, _, member, symbol) in packetDetails)
            {
                context.AddSource($"{fullyQualifiedName.Replace(':', '_')}Packet.g.cs",
                    SourceText.From(GeneratePacketSource(symbol, symbol.ContainingNamespace.ToString(), className),
                        Encoding.UTF8));
            }

            context.AddSource("PacketType.g.cs",
                SourceText.From(GeneratePacketTypeEnumSource(packetDetails), Encoding.UTF8));

            foreach (var groupName in allGroupNames.Distinct())
            {
                if (groupName == "*") continue; // Skip wildcard group
                var groupPackets = packetDetails
                    .Where(p => p.groupNames.Contains(groupName) || p.groupNames.Contains("*")).ToList();
                if (groupPackets.Any())
                {
                    context.AddSource($"I{groupName}PacketHandler.g.cs",
                        SourceText.From(GenerateGroupHandlerSource(groupName, groupPackets), Encoding.UTF8));
                }
            }
        }
    }

    private string GenerateGroupHandlerSource(string groupName,
        List<(string className, ushort Value, string fullyQualifiedName, List<string> groupNames, TypeDeclarationSyntax
            member, INamedTypeSymbol symbol)> groupPackets)
    {
        var sb = new IndentedStringBuilder();
        sb.AppendLine(AutoGenHeader);
        sb.AppendLine($"namespace {Namespace};");
        sb.AppendLine();

        sb.AppendLine($"public interface I{groupName}PacketHandler<in TUserData>");
        sb.EnterScope();
        foreach (var (name, id, fullName, _, _, _) in groupPackets)
        {
            sb.AppendLine($"/// <remarks>PacketType: {id} ({name})</remarks>");
            sb.AppendLine($"""/// <see cref="{fullName}"/>""");
            sb.AppendLine($"void Handle({fullName} message, TUserData userData);");
        }

        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Automatically handles the packet based on its PacketType.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine(
            "public void AutoHandle(PacketType packetType, scoped ref global::MemoryPack.MemoryPackReader reader, TUserData userData)");
        sb.EnterScope();
        sb.AppendLine("switch (packetType)");
        sb.EnterScope();
        foreach (var (name, _, fullName, _, _, _) in groupPackets)
        {
            sb.AppendLine($"case PacketType.{name}:");
            sb.Indent();
            sb.AppendLine($"Handle(reader.ReadPackable<{fullName}>(), userData);");
            sb.AppendLine("break;");
            sb.Unindent();
        }

        sb.AppendLine("default:");
        sb.Indent();
        sb.AppendLine("throw new global::System.ArgumentOutOfRangeException(nameof(packetType), packetType, null);");
        sb.Unindent();

        sb.ExitScope();
        sb.ExitScope();


        sb.ExitScope();
        return sb.ToString();
    }

    private string GeneratePacketTypeEnumSource(
        List<(string className, ushort Value, string fullyQualifiedName, List<string> groupNames, TypeDeclarationSyntax
            member, INamedTypeSymbol symbol)> packetDetails)
    {
        var sb = new IndentedStringBuilder();
        sb.AppendLine(AutoGenHeader);
        sb.AppendLine($"namespace {Namespace};");
        sb.AppendLine();
        sb.AppendLine("public enum PacketType : ushort");
        sb.EnterScope();
        foreach (var (name, id, fullName, groups, _, _) in packetDetails)
        {
            sb.AppendLine($"/// <remarks>Can be handled by: {string.Join(", ", groups)}</remarks>");
            sb.AppendLine($"""/// <see cref="{fullName}"/>""");
            sb.AppendLine($"{name} = {id},");
        }

        sb.ExitScope();
        return sb.ToString();
    }

    private bool CheckPackets(SourceProductionContext context,
        List<(string className, ushort Value, string fullyQualifiedName, List<string> groupNames, TypeDeclarationSyntax
            member, INamedTypeSymbol symbol)> packetDetails)
    {
        // Check for duplicate packet IDs within the same group
        var wildcardIds = new HashSet<ushort>();
        var packetIdGroups = new Dictionary<string, HashSet<ushort>>();
        foreach (var (name, id, _, groups, source, symbol) in packetDetails)
        {
            if(groups.Contains("*"))
                wildcardIds.Add(id);
        }
        
        foreach (var (name, id, _, groups, source, symbol) in packetDetails)
        {
            foreach (var group in groups)
            {
                if (!packetIdGroups.ContainsKey(group))
                {
                    packetIdGroups[group] = new HashSet<ushort>();
                }

                if (packetIdGroups[group].Contains(id) || (group != "*" && wildcardIds.Contains(id)))
                {
                    context.ReportDiagnostic(Diagnostic.Create(NetworkGeneratorRules.InvalidAttributeRule,
                        source.GetLocation(), name,
                        $"Duplicate packet ID {id} found in group '{group}'"));
                    return false;
                }

                packetIdGroups[group].Add(id);
            }
        }

        return true;
    }

    private string GeneratePacketSource(INamedTypeSymbol symbol, string namespaceName, string className)
    {
        var sb = new IndentedStringBuilder();

        sb.AppendLine(AutoGenHeader);

        // Add required usings
        sb.AppendLine("using NetworkPackets;");
        sb.AppendLine("using System.Buffers;");
        sb.AppendLine("using System.Diagnostics;");
        sb.AppendLine("using MemoryPack;");
        sb.AppendLine("using MemoryPack.Internal;");
        sb.AppendLine();

        sb.AppendLine($"namespace {namespaceName};");
        sb.AppendLine();

        sb.AppendLine($"partial class {symbol.ContainingType.Name}");
        sb.EnterScope();

        var accessibility = symbol.DeclaredAccessibility.ToString().ToLowerInvariant();
        sb.AppendLine($"{accessibility} partial record struct {className} : IPacket");
        sb.EnterScope();

        // ToMessage Method
        sb.AppendLine("public SerializedMessage ToMessage()");
        sb.EnterScope();
        sb.AppendLine("var serializer = new SerializedMessage();");
        sb.AppendLine(
            "var writer = new MemoryPackWriter<ReusableLinkedArrayBufferWriter>(ref serializer.Writer, serializer.State);");
        sb.AppendLine("Serialize(ref writer);");
        sb.AppendLine("return serializer;");
        sb.ExitScope();
        sb.AppendLine();

        // Serialize Method
        sb.AppendLine(
            "public void Serialize(scoped ref MemoryPackWriter<ReusableLinkedArrayBufferWriter> writer, bool flush = true)");
        sb.EnterScope();
        sb.AppendLine($"writer.WriteUnmanaged(PacketType.{className});");
        sb.AppendLine("writer.WritePackable(in this);");
        sb.AppendLine("if (flush) writer.Flush();");
        sb.ExitScope();
        sb.AppendLine();

        // Send Methods
        sb.AppendLine("public void Send(IQConnection connection)");
        sb.EnterScope();
        sb.AppendLine("using var msg = ToMessage();");
        sb.AppendLine("connection.Send(msg);");
        sb.ExitScope();

        sb.AppendLine("public void SendToAll(IQServer server)");
        sb.EnterScope();
        sb.AppendLine("using var msg = ToMessage();");
        sb.AppendLine("server.SendToAll(msg);");
        sb.ExitScope();
        sb.AppendLine();

        // Deserialize static factory
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Deserializes the packet from the given data span.");
        sb.AppendLine("/// <remarks>Assumes the PacketType prefix has already been read.</remarks>");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"public static {className} Deserialize(global::System.ReadOnlySpan<byte> data)");
        sb.EnterScope();
        sb.AppendLine($"var packet = new {className}();");
        sb.AppendLine("var read = global::MemoryPack.MemoryPackSerializer.Deserialize(data, ref packet);");
        sb.AppendLine(
            $"Debug.Assert(read == data.Length, $\"Did not read entire buffer when deserializing {className}. Read {{read}} of {{data.Length}} bytes.\");");
        sb.AppendLine("return packet;");
        sb.ExitScope();
        sb.AppendLine();

        sb.ExitScope();
        sb.ExitScope();

        return sb.ToString();
    }
}