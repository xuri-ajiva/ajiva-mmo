using System;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;


namespace WgslGenerator;

/// <summary>
/// A sample source generator that creates a custom report based on class properties. The target class should be annotated with the 'Generators.ReportAttribute' attribute.
/// When using the source code as a baseline, an incremental source generator is preferable because it reduces the performance overhead.
/// </summary>
[Generator]
public class SourceGeneratorWithAttributes : IIncrementalGenerator
{
    private const string Namespace = "Generators";
    private const string AttributeName = "GenerateShaderAttribute";

    private const string AttributeSourceCode =
        $$"""
          // <auto-generated/>
          #pragma warning disable CS9113
          using System;
          namespace {{Namespace}};

          [AttributeUsage(AttributeTargets.Class)]
          public class {{AttributeName}} : Attribute;

          [AttributeUsage(AttributeTargets.Field | AttributeTargets.Parameter)]
          public partial class Builtin(string name) : Attribute;

          [AttributeUsage(AttributeTargets.Field | AttributeTargets.Parameter)]
          public partial class Location(uint location) : Attribute;

          [AttributeUsage(AttributeTargets.Method)]
          public partial class VertexShader : Attribute;

          [AttributeUsage(AttributeTargets.Method)]
          public partial class FragmentShader : Attribute;

          [AttributeUsage(AttributeTargets.Field | AttributeTargets.Property)]
          public partial class Group(uint id) : Attribute;

          [AttributeUsage(AttributeTargets.Field | AttributeTargets.Property)]
          public partial class Binding(uint id) : Attribute;

          [AttributeUsage(AttributeTargets.Field | AttributeTargets.Property)]
          public partial class Access(ShaderAccess access) : Attribute;

          [Flags]
          public enum ShaderAccess
          {
              Uniform,
              Storage,
              Read,
              Write,
          }
          #pragma warning restore CS9113
          """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx => ctx.AddSource(
            "Attributes.g.cs",
            SourceText.From(AttributeSourceCode, Encoding.UTF8)));

        var provider = context.SyntaxProvider
            .CreateSyntaxProvider(
                (s, _) => s is ClassDeclarationSyntax,
                (ctx, _) => GetClassDeclarationForSourceGen(ctx))
            .Where(t => t.attributeFound)
            .Select((t, _) => t.Item1);

        context.RegisterSourceOutput(context.CompilationProvider.Combine(provider.Collect()),
            (ctx, t) => GenerateCode(ctx, t.Left, t.Right));
    }

    /// <summary>
    /// Checks whether the Node is annotated with the [Report] attribute and maps syntax context to the specific node type (ClassDeclarationSyntax).
    /// </summary>
    /// <param name="context">Syntax context, based on CreateSyntaxProvider predicate</param>
    /// <returns>The specific cast and whether the attribute was found.</returns>
    private static (ClassDeclarationSyntax, bool attributeFound) GetClassDeclarationForSourceGen(
        GeneratorSyntaxContext context)
    {
        var classDeclarationSyntax = (ClassDeclarationSyntax)context.Node;

        // Go through all attributes of the class.
        foreach (AttributeListSyntax attributeListSyntax in classDeclarationSyntax.AttributeLists)
        foreach (AttributeSyntax attributeSyntax in attributeListSyntax.Attributes)
        {
            if (ModelExtensions.GetSymbolInfo(context.SemanticModel, attributeSyntax).Symbol is not IMethodSymbol
                attributeSymbol)
                continue; // if we can't get the symbol, ignore it

            string attributeName = attributeSymbol.ContainingType.ToDisplayString();

            // Check the full name of the [Report] attribute.
            if (attributeName == $"{Namespace}.{AttributeName}")
                return (classDeclarationSyntax, true);
        }

        return (classDeclarationSyntax, false);
    }

    /// <summary>
    /// Generate code action.
    /// It will be executed on specific nodes (ClassDeclarationSyntax annotated with the [Report] attribute) changed by the user.
    /// </summary>
    /// <param name="context">Source generation context used to add source files.</param>
    /// <param name="compilation">Compilation used to provide access to the Semantic Model.</param>
    /// <param name="classDeclarations">Nodes annotated with the [Report] attribute that trigger the generate action.</param>
    private void GenerateCode(SourceProductionContext context, Compilation compilation,
        ImmutableArray<ClassDeclarationSyntax> classDeclarations)
    {
        foreach (var classDeclarationSyntax in classDeclarations)
        {
            var wgslVisitor = new WgslVisitor(context, compilation, classDeclarationSyntax);
            classDeclarationSyntax.Accept(wgslVisitor);
            var shaderSource =
                $""""
                 """
                 {wgslVisitor.GetResult()}
                 """    
                 """";

            //var bindings = wgslVisitor.GetBindingGroups();
            
            // Generate a partial class with a ShaderSource constant
            var className = classDeclarationSyntax.Identifier.Text;

            // Get namespace from semantic model
            var semanticModel = compilation.GetSemanticModel(classDeclarationSyntax.SyntaxTree);
            var symbol = ModelExtensions.GetDeclaredSymbol(semanticModel, classDeclarationSyntax);
            var namespaceName = symbol.ContainingNamespace.ToDisplayString();

            var assingment = EqualsValueClause(
                LiteralExpression(
                    SyntaxKind.StringLiteralExpression,
                    Literal(shaderSource, shaderSource)));

            
            // Using compilation unit to build the partial class
            var partialClass = CompilationUnit()
                .AddUsings(UsingDirective(ParseName("System")))
                .AddMembers(FileScopedNamespaceDeclaration(ParseName(namespaceName)),
                    ClassDeclaration(className)
                        .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.PartialKeyword))
                        .AddMembers(FieldDeclaration(
                            VariableDeclaration(ParseTypeName("string"))
                                .AddVariables(VariableDeclarator("ShaderSource")
                                    .WithInitializer(assingment))
                        ).AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.ConstKeyword)))
                        //.AddMembers(layoutDeclarations)
                       // .AddMembers(bindGroupCreators)
                );

            var sourceText = partialClass.NormalizeWhitespace().ToFullString();
            context.AddSource($"{className}.g.cs", SourceText.From(sourceText, Encoding.UTF8));
        }
    }
}
